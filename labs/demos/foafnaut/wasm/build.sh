#!/bin/bash
# Assemble foaf-check.wat and write the two copies of its bytes that are checked in:
#   formal/lean4/L4Factoidal/WasmVM/Proofs/FoafCheckBytes.lean  (the bytes the proof is about)
#   labs/demos/foafnaut/pages/foaf-explorer-verified.html         (the bytes the page runs, as hex
#                                                                  between its BEGIN/END markers)
# Both are generated from the .wat; `build.sh --check` re-assembles and fails if either
# copy differs, so a checked-in copy is always the assembler's output for the source.
# Assembler: wabt `wat2wasm` (Apache-2.0), pinned below. The proof does not trust it:
# FoafCheckBinary.lean decodes the bytes with WasmVM's decoder in the Lean kernel.
# Record: docs/designissues/2026-11-09-verified-foaf-layout.md.
set -euo pipefail
WABT_VERSION=1.0.42
here=$(cd "$(dirname "$0")" && pwd)
root=$(cd "$here/../../../.." && pwd)
check=0; [ "${1:-}" = "--check" ] && check=1
have=$(wat2wasm --version 2>/dev/null || echo none)
if [ "$have" != "$WABT_VERSION" ]; then
  echo "build.sh: needs wabt wat2wasm $WABT_VERSION (found: $have); brew install wabt or https://github.com/WebAssembly/wabt/releases/tag/$WABT_VERSION" >&2
  exit 2
fi
tmp=$(mktemp -d); trap 'rm -rf "$tmp"' EXIT
wat2wasm "$here/foaf-check.wat" -o "$tmp/foaf-check.wasm"
python3 - "$tmp/foaf-check.wasm" "$tmp" "$WABT_VERSION" <<'PY'
import sys, hashlib
wasm, out, ver = sys.argv[1], sys.argv[2], sys.argv[3]
b = open(wasm, 'rb').read()
sha = hashlib.sha256(b).hexdigest()
rows = [', '.join(str(x) for x in b[i:i+24]) for i in range(0, len(b), 24)]
lean = ('/- GENERATED by labs/demos/foafnaut/wasm/build.sh from foaf-check.wat with wabt wat2wasm %s.\n'
        'Do not edit: run build.sh; build.sh --check fails if this differs from the assembler output.\n'
        '%d bytes, SHA-256 %s. -/\n'
        'namespace L4Factoidal.WasmVM.Proofs.FoafCheck\n\n'
        '/-- The assembled `foaf-check.wasm`. -/\n'
        'def checkBytes : ByteArray := ⟨#[\n  ' % (ver, len(b), sha) + ',\n  '.join(rows) + ']⟩\n\n'
        'end L4Factoidal.WasmVM.Proofs.FoafCheck\n')
open(out + '/FoafCheckBytes.lean', 'w').write(lean)
hexs = b.hex()
js = ("  var FOAF_CHECK_WASM_HEX = // %d bytes, SHA-256 %s, wabt wat2wasm %s\n" % (len(b), sha, ver) +
      ' +\n'.join("    '%s'" % hexs[i:i+96] for i in range(0, len(hexs), 96)) + ';\n')
open(out + '/hex.js', 'w').write(js)
PY
leanf="$root/formal/lean4/L4Factoidal/WasmVM/Proofs/FoafCheckBytes.lean"
page="$root/labs/demos/foafnaut/pages/foaf-explorer-verified.html"
python3 - "$page" "$tmp/hex.js" "$tmp/page.html" <<'PY'
import sys
page, hexjs, out = sys.argv[1], sys.argv[2], sys.argv[3]
s = open(page).read()
b = s.index('/* foaf-check.wasm: BEGIN')
b = s.index('\n', b) + 1
e = s.index('  /* foaf-check.wasm: END */')
open(out, 'w').write(s[:b] + open(hexjs).read() + s[e:])
PY
if [ $check = 1 ]; then
  ok=1
  cmp -s "$tmp/FoafCheckBytes.lean" "$leanf" || { echo "build.sh --check: $leanf differs from the assembler output" >&2; ok=0; }
  cmp -s "$tmp/page.html" "$page" || { echo "build.sh --check: the bytes in $page differ from the assembler output" >&2; ok=0; }
  [ $ok = 1 ] && echo "foaf-check: checked-in bytes match wat2wasm $WABT_VERSION output"
  [ $ok = 1 ]
else
  cp "$tmp/FoafCheckBytes.lean" "$leanf"
  cp "$tmp/page.html" "$page"
  echo "wrote $leanf and the bytes in $page ($(wc -c < "$tmp/foaf-check.wasm" | tr -d ' ') bytes)"
fi
