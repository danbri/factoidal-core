#!/usr/bin/env python3
"""Write WebWasmSample.lean: a few files of the official WebAssembly core tests,
for the engine's in-place check (`wasmSpecSample`, page foafnaut:wasm).

Input: the JSON command lists and .wasm files under
third_party/wasm-spec/test/core-json/ (made by `wasm-tools json-from-wast`; the same
input as `lake exe wasmvm-spectest`). Kept: binary modules, assert_return,
assert_trap, assert_exhaustion, and assert_invalid / assert_malformed of binary
modules. Each module file is inlined as hex. Usage, from the repository root:

  python3 labs/demos/foafnaut/web-wasm/make-spec-sample.py [--check]
"""
import json, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[4]
CORE = ROOT / "third_party/wasm-spec/test/core-json"
OUT = ROOT / "labs/demos/foafnaut/WebWasmSample.lean"
FILES = ["fac", "i32", "i64", "conversions", "call", "loop"]
KEEP = {"module", "assert_return", "assert_trap", "assert_exhaustion", "assert_invalid", "assert_malformed"}

def sample():
    out = []
    for name in FILES:
        data = json.loads((CORE / name / f"{name}.json").read_text())
        mods, cmds = {}, []
        for c in data["commands"]:
            if c["type"] not in KEEP: continue
            if c["type"] in ("module", "assert_invalid", "assert_malformed"):
                if c.get("module_type") != "binary": continue
                fn = c["filename"]
                mods[fn] = (CORE / name / fn).read_bytes().hex()
            keep = {k: c[k] for k in ("type", "line", "filename", "action", "expected", "text") if k in c}
            cmds.append(keep)
        out.append({"name": name, "modules": mods, "commands": cmds})
    return json.dumps(out, separators=(",", ":"), sort_keys=True)

def lean(text):
    esc = text.replace("\\", "\\\\").replace('"', '\\"')
    return ("/-\nGenerated by labs/demos/foafnaut/web-wasm/make-spec-sample.py from\n"
            "third_party/wasm-spec/test/core-json (files: " + ", ".join(FILES) + "). Do not edit.\n-/\n"
            "namespace WebWasmSample\n\n"
            "/-- The kept commands and their modules (hex), as JSON. -/\n"
            f"def text : String := \"{esc}\"\n\nend WebWasmSample\n")

if __name__ == "__main__":
    body = lean(sample())
    if "--check" in sys.argv[1:]:
        if OUT.read_text() != body: sys.exit(f"{OUT} is out of date: run {Path(__file__).name}")
    else:
        OUT.write_text(body)
        print(f"wrote {OUT} ({len(body)} bytes)")
