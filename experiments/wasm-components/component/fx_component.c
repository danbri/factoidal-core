/*
fx_component.c — binds the WIT world `factoidal:subset/subset` (wit-bindgen
C bindings in gen/) to the two Lean exports of lean/FxSubset.lean.

No RDF or SPARQL logic here: only Lean initialisation and the conversion
between component-model strings (ptr, len; UTF-8) and Lean strings.

Ownership: the canonical ABI gives the callee each argument string (malloc'd
by cabi_realloc), so this file frees it after the Lean string is made.
A returned string is malloc'd here and freed by the generated post-return
function. Lean's exports take OWNED arguments and return an owned object.
*/
#include <lean/lean.h>
#include <lean/mimalloc.h>
#include <stdlib.h>
#include <string.h>
#include "subset.h"   /* generated by wit-bindgen into the object directory */

void lean_initialize_runtime_module(void);
void lean_io_mark_end_initialization(void);
extern lean_object *FX_INIT_MODULE(uint8_t builtin);
extern lean_object *fx_parse(lean_object *text, lean_object *format, lean_object *base);
extern lean_object *fx_query(lean_object *nquads, lean_object *sparql);

static int g_init = 0;

static void fx_init(void) {
    if (g_init) return;
#ifndef FX_MI_PURGE
    /* Purge delay -1: mimalloc never schedules a purge, so it never reads the
       clock on free. Wasm cannot return memory to the host, so a purge only
       re-commits pages. Measured 2026-10-28 (RESULTS.md, "allocator clock"):
       with the default delay, Lean initialisation made 6,123
       wasi:clocks/monotonic-clock.now calls, each one a JavaScript call
       under jco. Build with -DFX_MI_PURGE to keep the default. */
    mi_option_set(mi_option_purge_delay, -1);
#endif
    lean_initialize_runtime_module();
    lean_object *res = FX_INIT_MODULE(1);
    if (!lean_io_result_is_ok(res)) { lean_io_result_show_error(res); abort(); }
    lean_dec_ref(res);
    lean_io_mark_end_initialization();
    g_init = 1;
}

/* Takes ownership of s. Invalid UTF-8 cannot arrive: the canonical ABI
   validates strings when it lifts them. */
static lean_object *to_lean(subset_string_t *s) {
    lean_object *o = lean_mk_string_from_bytes((const char *)s->ptr, s->len);
    subset_string_free(s);
    return o;
}

/* Consumes o, a Lean string. */
static void from_lean(lean_object *o, subset_string_t *ret) {
    size_t n = lean_string_size(o) - 1;
    uint8_t *p = malloc(n ? n : 1);
    if (!p) abort();
    memcpy(p, lean_string_cstr(o), n);
    lean_dec(o);
    ret->ptr = p;
    ret->len = n;
}

bool exports_factoidal_subset_rdf_parse(subset_string_t *text, subset_string_t *format,
                                        subset_string_t *base, subset_string_t *ret,
                                        subset_string_t *err) {
    fx_init();
    lean_object *r = fx_parse(to_lean(text), to_lean(format), to_lean(base));
    /* Except String String: tag 0 = error, tag 1 = ok; field 0 is the string. */
    unsigned tag = lean_obj_tag(r);
    lean_object *s = lean_ctor_get(r, 0);
    lean_inc(s);
    lean_dec(r);
    if (tag == 1) { from_lean(s, ret); return true; }
    from_lean(s, err);
    return false;
}

void exports_factoidal_subset_rdf_query(subset_string_t *nquads, subset_string_t *sparql,
                                        subset_string_t *ret) {
    fx_init();
    from_lean(fx_query(to_lean(nquads), to_lean(sparql)), ret);
}
