// The format table: the engine's own list (op datasetFormats, via
// formats()) is checked cell by cell here, and README.md's table is
// generated from it. Run with UPDATE_FORMATS_TABLE=1 to rewrite the README
// block; without it, a README that differs from the engine's list fails.

import test from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync, writeFileSync } from 'node:fs';
import * as f from '../index.mjs';

const MISSING_WRITERS = 'https://github.com/danbri/factoidal/issues/883';

function xfail(name, issueUrl, fn) {
  test(`xfail: ${name} (${issueUrl})`, async (t) => {
    let failed = false;
    try { await fn(); } catch (err) { failed = true; t.diagnostic(String(err && err.message)); }
    assert.ok(failed, `unexpected pass: ${name} now works; flip this xfail to an assertion and close ${issueUrl}`);
  });
}

const RDF11 = '<http://e/a> <http://e/p> "x"@en .\n<http://e/a> <http://e/q> _:b .\n' +
  '_:b <http://e/r> "1"^^<http://www.w3.org/2001/XMLSchema#integer> .\n';
const RDF11_Q = RDF11 + '<http://e/a> <http://e/p> <http://e/o> <http://e/g> .\n';
const RDF12 = '<http://e/a> <http://e/says> <<( <http://e/s> <http://e/p> <http://e/o> )>> .\n';

const READ_TAG = { nquads: 'nquads', ntriples: 'ntriples', turtle: 'turtle', trig: 'trig', rdfxml: 'rdfxml', jsonld: 'jsonld' };
const RESULTS = { 'sparql-results-json': 'json', 'sparql-results-xml': 'xml', 'sparql-results-csv': 'csv', 'sparql-results-tsv': 'tsv' };

const table = await f.formats();

function markdown(rows) {
  const yn = (b) => (b ? 'yes' : 'no');
  const lines = ['| format | read RDF 1.1 | read RDF 1.2 | write RDF 1.1 | write RDF 1.2 | engine |',
    '|---|---|---|---|---|---|'];
  for (const r of rows) {
    lines.push(`| ${r.name} | ${yn(r.read11)} | ${yn(r.read12)} | ${yn(r.write11)} | ${yn(r.write12)} | ${r.engine} |`);
  }
  return lines.join('\n');
}

test('README format table is the engine list', () => {
  const path = new URL('../README.md', import.meta.url);
  const readme = readFileSync(path, 'utf8');
  const start = '<!-- formats-table:start (generated by test/formats-table.test.mjs) -->';
  const end = '<!-- formats-table:end -->';
  const i = readme.indexOf(start);
  const j = readme.indexOf(end);
  assert.ok(i >= 0 && j > i, 'README.md has the formats-table markers');
  const want = `${start}\n${markdown(table)}\n${end}`;
  const have = readme.slice(i, j + end.length);
  if (have !== want && process.env.UPDATE_FORMATS_TABLE === '1') {
    writeFileSync(path, readme.slice(0, i) + want + readme.slice(j + end.length));
    return;
  }
  assert.equal(have, want, 'run UPDATE_FORMATS_TABLE=1 npm test to regenerate');
});

for (const row of table) {
  if (RESULTS[row.name]) {
    test(`results writer ${row.name}`, async () => {
      const ds = await f.parse(RDF11, { format: 'ntriples' });
      const out = await ds.query('SELECT ?o WHERE { <http://e/a> <http://e/p> ?o }', { output: RESULTS[row.name] });
      assert.ok(typeof out === 'string' ? out.length > 0 : out.head.vars[0] === 'o');
      ds.dispose();
    });
    continue;
  }
  if (row.write11) {
    test(`${row.name} writes RDF 1.1${row.read11 ? ' and reads it back' : ''}`, async () => {
      const src = (row.name === 'ntriples' || row.name === 'rdfxml') ? RDF11 : RDF11_Q;
      const ds = await f.parse(src, { format: 'nquads' });
      const text = await ds.serialize({ format: row.name, version: '1.1' });
      assert.ok(text.length > 0);
      if (row.read11) {
        const back = await f.parse(text, { format: READ_TAG[row.name] });
        assert.equal(await back.canonicalize(), await ds.canonicalize());
        back.dispose();
      }
      ds.dispose();
    });
  }
  const ds12 = () => f.parse(RDF12, { format: 'ntriples12' });
  if (row.write12) {
    test(`${row.name} writes RDF 1.2 and refuses it under version 1.1`, async () => {
      const ds = await ds12();
      const text = await ds.serialize({ format: row.name, version: '1.2' });
      if (row.read12) {
        const back = await f.parse(text, { format: `${READ_TAG[row.name]}12` });
        assert.equal(back.size, ds.size);
        assert.equal(await back.query('ASK { ?s ?p <<( <http://e/s> <http://e/p> <http://e/o> )>> }', { sparql12: true }), true);
        back.dispose();
      }
      await assert.rejects(ds.serialize({ format: row.name, version: '1.1' }), /RDF 1\.2/);
      ds.dispose();
    });
  } else if (row.write11 && row.name !== 'rdfc') {
    xfail(`${row.name} writes an RDF 1.2 triple term`, MISSING_WRITERS, async () => {
      const ds = await ds12();
      try { await ds.serialize({ format: row.name }); } finally { ds.dispose(); }
    });
  }
}

for (const name of ['hdt', 'n3', 'rdfa']) {
  xfail(`serialize writes ${name}`, MISSING_WRITERS, async () => {
    const ds = await f.parse(RDF11, { format: 'ntriples' });
    try { await ds.serialize({ format: name }); } finally { ds.dispose(); }
  });
}

xfail('csv2json (CSVW JSON output) is an npm function', MISSING_WRITERS, async () => {
  assert.equal(typeof f.csvwToJson, 'function');
});
