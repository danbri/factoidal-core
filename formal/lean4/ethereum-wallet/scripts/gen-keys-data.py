#!/usr/bin/env python3
"""Turn the published BIP-39 wordlist and the published key test vectors into Lean data.

Reads only files under third_party/testing/ethereum-wallet (see PROVENANCE.md there)
and writes two generated modules:

  EthereumWallet/Keys/Bip39English.lean   the 2048 English words as numbers
  EthereumWallet/Keys/KeysVectors.lean    BIP-39, BIP-32 and ERC-55 vectors as strings

This script only reformats published data. It computes no hash, key or address:
the expected values in the vectors are copied as published. `--check` regenerates
into memory and fails if the committed files differ (CI runs it).

A word is the number whose base-27 digits are its letters (a = 1 ... z = 26), most
significant first; the Lean side proves that reading the digits back gives the word.
"""
import hashlib
import json
import re
import sys
from pathlib import Path

PKG = Path(__file__).resolve().parent.parent
REPO = PKG.parent.parent.parent
SRC = REPO / "third_party" / "testing" / "ethereum-wallet"
PINS = {
    "bip-0039/english.txt": "2f5eed53a4727b4bf8880d8f3f199efc90e58503646d9ff8eff3a2ed3b24dbda",
    "bip-0039/vectors.json": "fa3b937b7cff9c9b8ecd3aa011faeb8d6dd67993174b72326e83f4de8fdb30f8",
    "bip-0032/bip-0032.mediawiki": "e5e00a8289db2f681052cf24a745320afc225e66b25d1e489a7c884d2fc7f11f",
    "erc-55/erc-55.md": "54a9b25ffcd12966c60d6abd6584734d2793734f266fbe41118e6ee52b05dc9e",
    "go-ethereum/v3_test_vector.json": "e3a43355d86d11c78f4025597b2e9012aa4fedfcfd07daeabd4b67fafbad5d7d",
}
HEADER = "-- GENERATED by scripts/gen-keys-data.py from third_party/testing/ethereum-wallet. Do not edit.\n"


def read(rel: str) -> str:
    data = (SRC / rel).read_bytes()
    digest = hashlib.sha256(data).hexdigest()
    if digest != PINS[rel]:
        raise SystemExit(f"{rel}: sha256 {digest} is not the pinned {PINS[rel]}")
    return data.decode("utf-8")


def lean_str(s: str) -> str:
    if not re.fullmatch(r"[ -~]*", s) or '"' in s or "\\" in s:
        raise SystemExit(f"not a plain ASCII string: {s!r}")
    return '"' + s + '"'


def word_code(word: str) -> int:
    if not re.fullmatch(r"[a-z]{1,8}", word):
        raise SystemExit(f"unexpected word: {word!r}")
    code = 0
    for ch in word:
        code = code * 27 + (ord(ch) - 96)
    return code


def wordlist_module() -> str:
    text = read("bip-0039/english.txt")
    words = text.split("\n")
    if words[-1] != "" or len(words) != 2049:
        raise SystemExit("english.txt: expected 2048 lines, each ended by a newline")
    words = words[:-1]
    out = [HEADER]
    out.append("/-\nThe BIP-39 English wordlist (specification data, MIT; source and sha256 in\n"
               "third_party/testing/ethereum-wallet/PROVENANCE.md) as 2048 numbers, in list order.\n"
               "A word is the number whose base-27 digits are its letters (a = 1 ... z = 26).\n-/\n\n")
    out.append("namespace EthereumWallet.Keys.Bip39.English\n\n")
    chunk = 128
    names = []
    for start in range(0, 2048, chunk):
        name = f"codes{start // chunk}"
        names.append(name)
        nums = [str(word_code(w)) for w in words[start:start + chunk]]
        lines = [", ".join(nums[i:i + 8]) for i in range(0, chunk, 8)]
        out.append(f"/-- Words {start} to {start + chunk - 1}: {words[start]} ... {words[start + chunk - 1]}. -/\n")
        out.append(f"def {name} : List Nat := [\n  " + ",\n  ".join(lines) + "]\n\n")
    out.append("/-- The whole list, in the order of the published file. -/\n")
    out.append("def codes : List Nat :=\n  " + " ++ ".join(names[:8]) + " ++\n  " + " ++ ".join(names[8:]) + "\n\n")
    out.append("/-- sha256 of the published `english.txt` (2048 lines, each ended by a newline). -/\n")
    out.append(f"def publishedSha256 : String :=\n  {lean_str(PINS['bip-0039/english.txt'])}\n\n")
    out.append("end EthereumWallet.Keys.Bip39.English\n")
    return "".join(out)


def bip32_vectors(text: str):
    """(vector number, seed hex, [(path, xpub, xprv)]) for vectors 1-4, and vector 5's invalid keys."""
    valid, invalid = [], []
    section = None
    seed = None
    chains = []
    path = None
    pub = None
    for line in text.split("\n"):
        m = re.fullmatch(r"===Test vector (\d+)===", line.strip())
        if m:
            if section is not None and seed is not None:
                valid.append((section, seed, chains))
            section, seed, chains, path, pub = int(m.group(1)), None, [], None, None
            continue
        if section is None:
            continue
        if line.startswith("==") and not line.startswith("==="):
            if seed is not None:
                valid.append((section, seed, chains))
            section, seed = None, None
            continue
        m = re.fullmatch(r"Seed \(hex\): ([0-9a-f]+)", line.strip())
        if m:
            seed = m.group(1)
            continue
        m = re.fullmatch(r"\* Chain (m[^ ]*)", line.strip())
        if m:
            path = m.group(1).replace("<sub>H</sub>", "'")
            continue
        m = re.fullmatch(r"\*\* ext pub: (\S+)", line.strip())
        if m:
            pub = m.group(1)
            continue
        m = re.fullmatch(r"\*\* ext prv: (\S+)", line.strip())
        if m:
            chains.append((path, pub, m.group(1)))
            continue
        m = re.fullmatch(r"\* ([1-9A-HJ-NP-Za-km-z]{100,}) \((.*)\)", line.strip())
        if m and section == 5:
            invalid.append((m.group(1), m.group(2)))
    counts = [len(c) for _, _, c in valid]
    if [n for n, _, _ in valid] != [1, 2, 3, 4] or counts != [6, 6, 2, 3] or len(invalid) != 16:
        raise SystemExit(f"bip-0032.mediawiki: unexpected vector layout {counts} {len(invalid)}")
    return valid, invalid


def erc55_vectors(text: str):
    body = text.split("# Test Cases", 1)[1].split("```")[1]
    addrs = [line.strip() for line in body.split("\n") if line.startswith("0x")]
    if len(addrs) != 8:
        raise SystemExit("erc-55.md: expected 8 test addresses")
    return addrs


def vectors_module() -> str:
    out = [HEADER]
    out.append("/-\nPublished test vectors for the key modules, copied as published (sources, licences and\n"
               "sha256 in third_party/testing/ethereum-wallet/PROVENANCE.md). The mnemonics, seeds and\n"
               "extended private keys here are public test vectors: never use them for anything of value.\n-/\n\n")
    out.append("namespace EthereumWallet.Keys.Vectors\n\n")
    english = json.loads(read("bip-0039/vectors.json"))["english"]
    if len(english) != 24:
        raise SystemExit("vectors.json: expected 24 English vectors")
    out.append("/-- BIP-39 English vectors (python-mnemonic `vectors.json`, passphrase \"TREZOR\"):\n"
               "entropy hex, mnemonic, seed hex, BIP-32 master extended private key. -/\n")
    out.append("def bip39English : List (String × String × String × String) := [\n")
    out.append(",\n".join("  (" + ",\n   ".join(lean_str(x) for x in v) + ")" for v in english))
    out.append("]\n\n")
    valid, invalid = bip32_vectors(read("bip-0032/bip-0032.mediawiki"))
    out.append("/-- BIP-32 test vectors 1 to 4: vector number, seed hex, then per chain the path,\n"
               "the extended public key and the extended private key. -/\n")
    out.append("def bip32 : List (Nat × String × List (String × String × String)) := [\n")
    blocks = []
    for number, seed, chains in valid:
        rows = ",\n".join("    (" + ",\n     ".join(lean_str(x) for x in c) + ")" for c in chains)
        blocks.append(f"  ({number}, {lean_str(seed)}, [\n{rows}])")
    out.append(",\n".join(blocks))
    out.append("]\n\n")
    out.append("/-- BIP-32 test vector 5: extended keys that must be refused, with the published reason. -/\n")
    out.append("def bip32Invalid : List (String × String) := [\n")
    out.append(",\n".join(f"  ({lean_str(k)},\n   {lean_str(why)})" for k, why in invalid))
    out.append("]\n\n")
    out.append("/-- ERC-55 test cases: checksummed addresses. -/\n")
    out.append("def erc55 : List String := [\n")
    out.append(",\n".join("  " + lean_str(a) for a in erc55_vectors(read("erc-55/erc-55.md"))))
    out.append("]\n\n")
    out.append("end EthereumWallet.Keys.Vectors\n")
    return "".join(out)


def embedded_keystore_vectors_stale() -> bool:
    """The keystore tests embed the geth vector file as a raw string: it must be the vendored text."""
    source = (PKG / "EthereumWallet" / "Keys" / "KeystoreTests.lean").read_text()
    opening = 'def gethVectorsText : String := r#"'
    start = source.index(opening) + len(opening)
    return source[start:source.index('"#', start)] != read("go-ethereum/v3_test_vector.json")


def main() -> int:
    targets = {
        PKG / "EthereumWallet" / "Keys" / "Bip39English.lean": wordlist_module(),
        PKG / "EthereumWallet" / "Keys" / "KeysVectors.lean": vectors_module(),
    }
    check = "--check" in sys.argv[1:]
    bad = 0
    for path, text in targets.items():
        if check:
            if not path.exists() or path.read_text() != text:
                print(f"STALE {path.relative_to(REPO)}: run scripts/gen-keys-data.py")
                bad += 1
        else:
            path.write_text(text)
            print(f"wrote {path.relative_to(REPO)}")
    if embedded_keystore_vectors_stale():
        print("STALE EthereumWallet/Keys/KeystoreTests.lean: gethVectorsText is not the vendored v3_test_vector.json")
        bad += 1
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
