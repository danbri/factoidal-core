#!/usr/bin/env bash
# tests/vc-di-eddsa/run.sh — run the vendored W3C vc-di-eddsa-test-suite
# (third_party/testing/vc-di-eddsa/) against bin/vc-api-shim/server.mjs,
# eddsa-rdfc-2022 (routes /credentials/*, the original shim path) and
# eddsa-jcs-2022 (routes /eddsa-jcs-2022/credentials/*, the Lean cryptosuite
# table of formal/lean4/L4Factoidal/VC/Cryptosuite.lean).
#
# Files run: 05-di-rdfc-create, 15-di-rdfc-verify, 70-data-model,
# 80-algorithms. Not run: 30-rdfc-interop.js and 60-jcs-interop.js, the
# interoperability files, which need other implementations' endpoints
# (settings.enableInteropTests is false). Until 2026-10-28 the vendored copy
# (769275c9) crashed at load in 70 and 80 (structuredClone DataCloneError in
# tests/vc-generator/contexts.js); the refreshed copy (1e86cc4c) loads.
#
# Requires: `npm install` already run in third_party/testing/vc-di-eddsa
# (see that directory's PROVENANCE.md).
set -euo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
SUITE_DIR="$REPO_ROOT/third_party/testing/vc-di-eddsa"
PORT="${VC_DI_EDDSA_PORT:-40447}"
RESULT_JSON="$REPO_ROOT/docs/test-results/by-suite/vc-di-eddsa.json"
MOCHA_JSON="$(mktemp)"
SHIM_LOG="$(mktemp)"

if [[ ! -d "$SUITE_DIR/node_modules" ]]; then
  echo "FAIL: $SUITE_DIR/node_modules missing — run: (cd $SUITE_DIR && npm install)"
  exit 1
fi

cleanup() {
  if [[ -n "${SHIM_PID:-}" ]] && kill -0 "$SHIM_PID" 2>/dev/null; then
    kill "$SHIM_PID" 2>/dev/null || true
    wait "$SHIM_PID" 2>/dev/null || true
  fi
  rm -f "$MOCHA_JSON" "$SHIM_LOG"
}
trap cleanup EXIT

node "$REPO_ROOT/bin/vc-api-shim/server.mjs" --port "$PORT" > "$SHIM_LOG" 2>&1 &
SHIM_PID=$!
for _ in $(seq 1 50); do
  grep -q "vc-api-shim listening on" "$SHIM_LOG" 2>/dev/null && break
  sleep 0.2
done
if ! grep -q "vc-api-shim listening on" "$SHIM_LOG" 2>/dev/null; then
  echo "FAIL: shim did not start"
  cat "$SHIM_LOG"
  exit 1
fi
ISSUER_DID="$(grep -o 'issuer=did:key:[A-Za-z0-9]*' "$SHIM_LOG" | head -1 | sed 's/issuer=//')"

cat > "$SUITE_DIR/localConfig.cjs" << EOF
/*! Generated by tests/vc-di-eddsa/run.sh (task #88). Not committed. */
const baseUrl = process.env.BASE_URL || 'http://localhost:$PORT';
module.exports = {
  settings: { enableInteropTests: false, testAllImplementations: false },
  implementations: [{
    name: 'Factoidal',
    implementation: 'Factoidal VC-API shim',
    issuers: [{
      id: '$ISSUER_DID',
      endpoint: \`\${baseUrl}/credentials/issue\`,
      supports: { vc: ['1.1', '2.0'] },
      tags: ['eddsa-rdfc-2022']
    }, {
      id: '$ISSUER_DID',
      endpoint: \`\${baseUrl}/eddsa-jcs-2022/credentials/issue\`,
      supports: { vc: ['1.1', '2.0'] },
      tags: ['eddsa-jcs-2022']
    }],
    verifiers: [{
      id: '$ISSUER_DID',
      endpoint: \`\${baseUrl}/credentials/verify\`,
      tags: ['eddsa-rdfc-2022']
    }, {
      id: '$ISSUER_DID',
      endpoint: \`\${baseUrl}/eddsa-jcs-2022/credentials/verify\`,
      tags: ['eddsa-jcs-2022']
    }]
  }]
};
EOF

cd "$SUITE_DIR"
MOCHA_RC=0
timeout 300 npx mocha tests/05-di-rdfc-create.js tests/15-di-rdfc-verify.js \
  tests/70-data-model.js tests/80-algorithms.js \
  --timeout 15000 --reporter json --reporter-option "output=$MOCHA_JSON" >/dev/null 2>&1 || MOCHA_RC=$?

python3 - "$MOCHA_JSON" "$RESULT_JSON" "$MOCHA_RC" << 'PYEOF'
import json, sys, datetime

mocha_path, out_path, mocha_rc = sys.argv[1], sys.argv[2], int(sys.argv[3])

try:
    with open(mocha_path) as f:
        d = json.load(f)
except Exception as e:
    print(f"FAIL: could not parse mocha JSON reporter output: {e}")
    sys.exit(1)

stats = d["stats"]
failures = [
    {"title": f["fullTitle"], "message": (f.get("err") or {}).get("message", "")}
    for f in d["failures"]
]

result = {
    "spec": "https://w3c.github.io/vc-di-eddsa-test-suite/",
    "suite": "vc-di-eddsa (eddsa-rdfc-2022 + eddsa-jcs-2022: create, verify, data model, algorithms)",
    "runner": "tests/vc-di-eddsa/run.sh",
    "retrieved_at": datetime.datetime.now(datetime.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"),
    "pass": stats["passes"],
    "fail": stats["failures"],
    "skip": stats.get("pending", 0),
    "total": stats["tests"],
    "present": True,
    "not_run_files": [
        "30-rdfc-interop.js", "60-jcs-interop.js",
    ],
    "not_run_reason": "interoperability files: they need other implementations' endpoints (enableInteropTests false)",
    "failures": failures,
}

with open(out_path, "w") as f:
    json.dump(result, f, indent=2)
    f.write("\n")

print(f"vc-di-eddsa: {stats['passes']} pass, {stats['failures']} fail (out of {stats['tests']}) -> {out_path}")
PYEOF
