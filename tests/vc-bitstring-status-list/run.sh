#!/usr/bin/env bash
# tests/vc-bitstring-status-list/run.sh — run the vendored W3C
# vc-bitstring-status-list-test-suite (third_party/testing/vc-bitstring-status-list/)
# against bin/vc-api-shim/server.mjs, routes /bitstring-status-list/credentials/*
# (Bitstring Status List v1.0 in formal/lean4/L4Factoidal/VC/StatusList.lean;
# credentials secured with eddsa-rdfc-2022).
#
# The suite dereferences statusListCredential over https only, so the shim
# also listens with TLS, on a self-signed certificate that openssl makes for
# this run (the suite's document loader does not check certificates).
#
# Test files run: 10-data_model, 20-algorithms. Not run: 30-interop (needs
# other implementations).
#
# Requires: `npm install` already run in third_party/testing/vc-bitstring-status-list.
set -euo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
SUITE_DIR="$REPO_ROOT/third_party/testing/vc-bitstring-status-list"
PORT="${VC_BSL_PORT:-40449}"
TLS_PORT="${VC_BSL_TLS_PORT:-40450}"
TLS_DIR="$(mktemp -d)"
RESULT_JSON="$REPO_ROOT/docs/test-results/by-suite/vc-bitstring-status-list.json"
mkdir -p "$(dirname "$RESULT_JSON")"
MOCHA_JSON="$(mktemp)"
SHIM_LOG="$(mktemp)"

if [[ ! -d "$SUITE_DIR/node_modules" ]]; then
  echo "FAIL: $SUITE_DIR/node_modules missing — run: (cd $SUITE_DIR && npm install)"
  exit 1
fi

cleanup() {
  if [[ -n "${SHIM_PID:-}" ]] && kill -0 "$SHIM_PID" 2>/dev/null; then
    kill "$SHIM_PID" 2>/dev/null || true
    wait "$SHIM_PID" 2>/dev/null || true
  fi
  rm -rf "$MOCHA_JSON" "$SHIM_LOG" "$TLS_DIR"
}
trap cleanup EXIT

openssl req -x509 -newkey rsa:2048 -nodes -days 1 -subj "/CN=localhost" \
  -keyout "$TLS_DIR/key.pem" -out "$TLS_DIR/cert.pem" >/dev/null 2>&1
node "$REPO_ROOT/bin/vc-api-shim/server.mjs" --port "$PORT" --tls-port "$TLS_PORT" \
  --tls-key "$TLS_DIR/key.pem" --tls-cert "$TLS_DIR/cert.pem" > "$SHIM_LOG" 2>&1 &
SHIM_PID=$!
for _ in $(seq 1 50); do
  grep -q "vc-api-shim listening on" "$SHIM_LOG" 2>/dev/null && break
  sleep 0.2
done
if ! grep -q "vc-api-shim listening on" "$SHIM_LOG" 2>/dev/null; then
  echo "FAIL: shim did not start"
  cat "$SHIM_LOG"
  exit 1
fi
ISSUER_DID="$(grep -o 'issuer=did:key:[A-Za-z0-9]*' "$SHIM_LOG" | head -1 | sed 's/issuer=//')"
if [[ -z "$ISSUER_DID" ]]; then
  echo "FAIL: shim did not print issuer=did:key:..."
  cat "$SHIM_LOG"
  exit 1
fi

cat > "$SUITE_DIR/localConfig.cjs" << EOF
/*! Generated by tests/vc-bitstring-status-list/run.sh. Not committed. */
const baseUrl = process.env.BASE_URL || 'http://localhost:$PORT';
module.exports = {
  settings: { enableInteropTests: false, testAllImplementations: false },
  implementations: [{
    name: 'Factoidal',
    implementation: 'Factoidal VC-API shim',
    issuers: [{
      id: '$ISSUER_DID',
      endpoint: \`\${baseUrl}/bitstring-status-list/credentials/issue\`,
      tags: ['BitstringStatusList']
    }],
    verifiers: [{
      id: '$ISSUER_DID',
      endpoint: \`\${baseUrl}/bitstring-status-list/credentials/verify\`,
      tags: ['BitstringStatusList']
    }]
  }]
};
EOF

cd "$SUITE_DIR"
MOCHA_RC=0
timeout 300 npx mocha tests/10-data_model.js tests/20-algorithms.js \
  --timeout 15000 --reporter json --reporter-option "output=$MOCHA_JSON" >/dev/null 2>&1 || MOCHA_RC=$?

python3 - "$MOCHA_JSON" "$RESULT_JSON" "$MOCHA_RC" << 'PYEOF'
import json, sys, datetime

mocha_path, out_path, mocha_rc = sys.argv[1], sys.argv[2], int(sys.argv[3])

try:
    with open(mocha_path) as f:
        d = json.load(f)
except Exception as e:
    print(f"FAIL: could not parse mocha JSON reporter output: {e}")
    sys.exit(1)

stats = d["stats"]
failures = [
    {"title": f["fullTitle"], "message": (f.get("err") or {}).get("message", "")}
    for f in d["failures"]
]

result = {
    "spec": "https://w3c.github.io/vc-bitstring-status-list-test-suite/",
    "suite": "vc-bitstring-status-list (data model + algorithms)",
    "runner": "tests/vc-bitstring-status-list/run.sh",
    "retrieved_at": datetime.datetime.now(datetime.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"),
    "pass": stats["passes"],
    "fail": stats["failures"],
    "skip": stats.get("pending", 0),
    "total": stats["tests"],
    "present": True,
    "not_run_files": [
        "30-interop.js",
    ],
    "not_run_reason": "interoperability tests need other implementations' endpoints",
    "failures": failures,
}

with open(out_path, "w") as f:
    json.dump(result, f, indent=2)
    f.write("\n")

print(f"vc-bitstring-status-list: {stats['passes']} pass, {stats['failures']} fail (out of {stats['tests']}) -> {out_path}")
PYEOF
