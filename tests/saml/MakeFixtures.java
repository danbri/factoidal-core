// Makes the SAML 2.0 fixtures of formal/lean4/L4Factoidal/SAML/Fixtures.lean
// (https://github.com/danbri/factoidal/issues/926) with the JDK's XML
// Signature API (JSR 105), the producer Touchstone's harness identity
// provider uses (SamlAssertions.java there). Independent of the Lean code.
//
//   java tests/saml/MakeFixtures.java > formal/lean4/L4Factoidal/SAML/Fixtures.lean
//
// Each run makes a new RSA key, so the output changes; the Lean checks do not.
import java.io.StringWriter;
import java.math.BigInteger;
import java.nio.charset.StandardCharsets;
import java.security.*;
import java.security.interfaces.RSAPublicKey;
import java.time.Instant;
import java.util.*;
import javax.xml.XMLConstants;
import javax.xml.crypto.dsig.*;
import javax.xml.crypto.dsig.dom.DOMSignContext;
import javax.xml.crypto.dsig.keyinfo.*;
import javax.xml.crypto.dsig.spec.*;
import javax.xml.parsers.DocumentBuilderFactory;
import javax.xml.transform.*;
import javax.xml.transform.dom.DOMSource;
import javax.xml.transform.stream.StreamResult;
import org.w3c.dom.*;

public class MakeFixtures {
    static final String SAML = "urn:oasis:names:tc:SAML:2.0:assertion";
    static final long NB = 1761313600L;
    static KeyPair idp, attacker;

    public static void main(String[] a) throws Exception {
        KeyPairGenerator g = KeyPairGenerator.getInstance("RSA");
        g.initialize(2048);
        idp = g.generateKeyPair();
        attacker = g.generateKeyPair();
        Map<String, String> out = new LinkedHashMap<>();
        out.put("valid", enc(build("_a1", "https://id.example/end-user", idp, null)));
        Document d = build("_a2", "https://id.example/end-user", idp, null);
        nameId(d).setTextContent("https://id.example/other-user");
        out.put("altered", enc(d));
        Document u = assertion("_a3", "https://id.example/end-user");
        out.put("unsigned", enc(u));
        out.put("attackerKey", enc(build("_a4", "https://id.example/end-user", attacker, null)));
        out.put("comment", enc(build("_a5", "https://id.example/end-user", idp, "comment")));
        out.put("inclusive", enc(build("_a6", "https://id.example/end-user", idp, "inclusive")));
        // Wrapping 1: an unsigned assertion naming another subject, with the
        // signed one inside it.
        Document w = assertion("_evil", "https://id.example/attacker");
        Node signed = w.importNode(build("_a7", "https://id.example/end-user", idp, null).getDocumentElement(), true);
        w.getDocumentElement().appendChild(signed);
        out.put("wrapChild", enc(w));
        // Wrapping 2: the same, with the outer assertion taking the signed
        // assertion's ID and the signed assertion's signature.
        Document w2 = assertion("_a8", "https://id.example/attacker");
        Document s2 = build("_a8", "https://id.example/end-user", idp, null);
        Element sig = (Element) s2.getElementsByTagNameNS(XMLSignature.XMLNS, "Signature").item(0);
        Element outer = w2.getDocumentElement();
        Node issuer = outer.getElementsByTagNameNS(SAML, "Issuer").item(0);
        Element sigCopy = (Element) w2.importNode(sig, true);
        outer.insertBefore(sigCopy, issuer.getNextSibling());
        Element obj = w2.createElementNS(XMLSignature.XMLNS, "ds:Object");
        sigCopy.appendChild(obj);
        Element inner = (Element) w2.importNode(s2.getDocumentElement(), true);
        inner.removeChild(inner.getElementsByTagNameNS(XMLSignature.XMLNS, "Signature").item(0));
        obj.appendChild(inner);
        out.put("wrapObject", enc(w2));
        RSAPublicKey pk = (RSAPublicKey) idp.getPublic();
        StringBuilder b = new StringBuilder();
        b.append("/-\nL4Factoidal.SAML.Fixtures: SAML 2.0 assertions made by the JDK's XML\n")
         .append("Signature API (JSR 105), as Touchstone's harness identity provider makes\n")
         .append("them. Generated by `java tests/saml/MakeFixtures.java`; do not edit.\n")
         .append("NotBefore ").append(NB).append(", NotOnOrAfter ").append(NB + 300).append(".\n-/\n")
         .append("namespace L4Factoidal.SAML.Fixtures\n\n")
         .append("def idpN : String := \"").append(hex(pk.getModulus())).append("\"\n")
         .append("def idpE : String := \"").append(hex(pk.getPublicExponent())).append("\"\n");
        for (var e : out.entrySet()) {
            b.append("def ").append(e.getKey()).append(" : String :=\n  \"").append(e.getValue()).append("\"\n");
        }
        b.append("\nend L4Factoidal.SAML.Fixtures\n");
        System.out.print(b);
    }

    static String hex(BigInteger v) {
        String h = v.toString(16);
        return h.length() % 2 == 0 ? h : "0" + h;
    }

    static Element nameId(Document d) {
        return (Element) d.getElementsByTagNameNS(SAML, "NameID").item(0);
    }

    static String instant(long s) { return Instant.ofEpochSecond(s).toString(); }

    static Element child(Element p, String n) {
        Element e = p.getOwnerDocument().createElementNS(SAML, n);
        p.appendChild(e);
        return e;
    }

    static Document assertion(String id, String subjectId) throws Exception {
        DocumentBuilderFactory f = DocumentBuilderFactory.newInstance();
        f.setNamespaceAware(true);
        f.setFeature(XMLConstants.FEATURE_SECURE_PROCESSING, true);
        Document doc = f.newDocumentBuilder().newDocument();
        Element as = doc.createElementNS(SAML, "saml:Assertion");
        as.setAttributeNS(XMLConstants.XMLNS_ATTRIBUTE_NS_URI, "xmlns:saml", SAML);
        as.setAttribute("ID", id);
        as.setIdAttribute("ID", true);
        as.setAttribute("Version", "2.0");
        as.setAttribute("IssueInstant", instant(NB));
        doc.appendChild(as);
        child(as, "saml:Issuer").setTextContent("https://idp.example");
        Element subject = child(as, "saml:Subject");
        Element nid = child(subject, "saml:NameID");
        nid.setAttribute("Format", "urn:oasis:names:tc:SAML:2.0:nameid-format:persistent");
        nid.setTextContent(subjectId);
        Element sc = child(subject, "saml:SubjectConfirmation");
        sc.setAttribute("Method", "urn:oasis:names:tc:SAML:2.0:cm:bearer");
        Element scd = child(sc, "saml:SubjectConfirmationData");
        scd.setAttribute("NotOnOrAfter", instant(NB + 300));
        scd.setAttribute("Recipient", "https://app.example/SAML");
        Element c = child(as, "saml:Conditions");
        c.setAttribute("NotBefore", instant(NB));
        c.setAttribute("NotOnOrAfter", instant(NB + 300));
        Element ar = child(c, "saml:AudienceRestriction");
        child(ar, "saml:Audience").setTextContent("https://app.example/SAML");
        child(ar, "saml:Audience").setTextContent("https://as.example");
        Element st = child(as, "saml:AuthnStatement");
        st.setAttribute("AuthnInstant", instant(NB));
        child(child(st, "saml:AuthnContext"), "saml:AuthnContextClassRef")
            .setTextContent("urn:oasis:names:tc:SAML:2.0:ac:classes:unspecified");
        return doc;
    }

    /** variant: null, "comment" (a comment inside NameID, signed), "inclusive" (an InclusiveNamespaces PrefixList). */
    static Document build(String id, String subjectId, KeyPair key, String variant) throws Exception {
        Document doc = assertion(id, subjectId);
        Element as = doc.getDocumentElement();
        if ("comment".equals(variant)) {
            Element nid = nameId(doc);
            nid.appendChild(doc.createComment("x"));
            nid.appendChild(doc.createTextNode(".attacker.example"));
        }
        if ("inclusive".equals(variant)) {
            as.setAttributeNS(XMLConstants.XMLNS_ATTRIBUTE_NS_URI, "xmlns:xs", "http://www.w3.org/2001/XMLSchema");
        }
        XMLSignatureFactory fac = XMLSignatureFactory.getInstance("DOM");
        TransformParameterSpec tps = "inclusive".equals(variant)
            ? new ExcC14NParameterSpec(List.of("xs")) : null;
        Reference ref = fac.newReference("#" + id, fac.newDigestMethod(DigestMethod.SHA256, null),
            List.of(fac.newTransform(Transform.ENVELOPED, (TransformParameterSpec) null),
                    fac.newTransform(CanonicalizationMethod.EXCLUSIVE, tps)), null, null);
        SignedInfo si = fac.newSignedInfo(
            fac.newCanonicalizationMethod(CanonicalizationMethod.EXCLUSIVE, (C14NMethodParameterSpec) null),
            fac.newSignatureMethod(SignatureMethod.RSA_SHA256, null), List.of(ref));
        KeyInfoFactory kif = fac.getKeyInfoFactory();
        KeyInfo ki = kif.newKeyInfo(List.of(kif.newKeyValue(key.getPublic())));
        Node subject = as.getElementsByTagNameNS(SAML, "Subject").item(0);
        DOMSignContext ctx = new DOMSignContext(key.getPrivate(), as, subject);
        ctx.setDefaultNamespacePrefix("ds");
        fac.newXMLSignature(si, ki).sign(ctx);
        return doc;
    }

    static String enc(Document doc) throws Exception {
        Transformer t = TransformerFactory.newInstance().newTransformer();
        t.setOutputProperty(OutputKeys.OMIT_XML_DECLARATION, "yes");
        StringWriter w = new StringWriter();
        t.transform(new DOMSource(doc), new StreamResult(w));
        return Base64.getUrlEncoder().withoutPadding().encodeToString(w.toString().getBytes(StandardCharsets.UTF_8));
    }
}
