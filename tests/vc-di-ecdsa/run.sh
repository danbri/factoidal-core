#!/usr/bin/env bash
# tests/vc-di-ecdsa/run.sh — run the vendored W3C vc-di-ecdsa-test-suite
# (third_party/testing/vc-di-ecdsa/) against bin/vc-api-shim/server.mjs
# started with `--suite-keys ecdsa`, scoped to ecdsa-rdfc-2019 and
# ecdsa-jcs-2019 with P-256 keys. ecdsa-sd-2023 is not run.
#
# Test files run: 05-rdfc-di-create, 15-rdfc-di-verify, 70-data-model,
# 90-algorithms-rdfc, 90-algorithms-jcs. The suite has no separate JCS
# create/verify files; JCS is exercised by 90-algorithms-jcs.js and by the
# tag-driven parts of 70-data-model.js.
# Not run: 30/60 interop (disabled by default), 35/45/90-sd/95 (ecdsa-sd-2023).
#
# Requires: `npm install` already run in third_party/testing/vc-di-ecdsa
# (see that directory's PROVENANCE.md; its postinstall clones the spec test
# vectors, so install needs network once).
set -euo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
SUITE_DIR="$REPO_ROOT/third_party/testing/vc-di-ecdsa"
PORT="${VC_DI_ECDSA_PORT:-40448}"
RESULT_JSON="$REPO_ROOT/docs/test-results/by-suite/vc-di-ecdsa.json"
MOCHA_JSON="$(mktemp)"
SHIM_LOG="$(mktemp)"

if [[ ! -d "$SUITE_DIR/node_modules" ]]; then
  echo "FAIL: $SUITE_DIR/node_modules missing — run: (cd $SUITE_DIR && npm install)"
  exit 1
fi

cleanup() {
  if [[ -n "${SHIM_PID:-}" ]] && kill -0 "$SHIM_PID" 2>/dev/null; then
    kill "$SHIM_PID" 2>/dev/null || true
    wait "$SHIM_PID" 2>/dev/null || true
  fi
  rm -f "$MOCHA_JSON" "$SHIM_LOG"
}
trap cleanup EXIT

node "$REPO_ROOT/bin/vc-api-shim/server.mjs" --suite-keys ecdsa --port "$PORT" > "$SHIM_LOG" 2>&1 &
SHIM_PID=$!
for _ in $(seq 1 50); do
  grep -q "vc-api-shim listening on" "$SHIM_LOG" 2>/dev/null && break
  sleep 0.2
done
if ! grep -q "vc-api-shim listening on" "$SHIM_LOG" 2>/dev/null; then
  echo "FAIL: shim did not start"
  cat "$SHIM_LOG"
  exit 1
fi
ISSUER_DID="$(grep -o 'issuer-p256=did:key:[A-Za-z0-9]*' "$SHIM_LOG" | head -1 | sed 's/issuer-p256=//')"
if [[ -z "$ISSUER_DID" ]]; then
  echo "FAIL: shim did not print issuer-p256=did:key:..."
  cat "$SHIM_LOG"
  exit 1
fi

cat > "$SUITE_DIR/localConfig.cjs" << EOF
/*! Generated by tests/vc-di-ecdsa/run.sh. Not committed. */
const baseUrl = process.env.BASE_URL || 'http://localhost:$PORT';
module.exports = {
  settings: { enableInteropTests: false, testAllImplementations: false },
  implementations: [{
    name: 'Factoidal',
    implementation: 'Factoidal VC-API shim',
    issuers: ['ecdsa-rdfc-2019', 'ecdsa-jcs-2019'].map(tag => ({
      id: '$ISSUER_DID',
      endpoint: \`\${baseUrl}/\${tag}/credentials/issue\`,
      supportedEcdsaKeyTypes: ['P-256'],
      supports: { vc: ['1.1', '2.0'] },
      tags: [tag]
    })),
    verifiers: ['ecdsa-rdfc-2019', 'ecdsa-jcs-2019'].map(tag => ({
      id: '$ISSUER_DID',
      endpoint: \`\${baseUrl}/\${tag}/credentials/verify\`,
      supportedEcdsaKeyTypes: ['P-256'],
      supports: { vc: ['1.1', '2.0'] },
      tags: [tag]
    }))
  }]
};
EOF

cd "$SUITE_DIR"
MOCHA_RC=0
timeout 300 npx mocha tests/05-rdfc-di-create.js tests/15-rdfc-di-verify.js \
  tests/70-data-model.js tests/90-algorithms-rdfc.js tests/90-algorithms-jcs.js \
  --timeout 15000 --reporter json > "$MOCHA_JSON" 2>/dev/null || MOCHA_RC=$?

python3 - "$MOCHA_JSON" "$RESULT_JSON" "$MOCHA_RC" << 'PYEOF'
import json, sys, datetime

mocha_path, out_path, mocha_rc = sys.argv[1], sys.argv[2], int(sys.argv[3])

try:
    with open(mocha_path) as f:
        d = json.load(f)
except Exception as e:
    print(f"FAIL: could not parse mocha JSON reporter output: {e}")
    sys.exit(1)

stats = d["stats"]
failures = [
    {"title": f["fullTitle"], "message": (f.get("err") or {}).get("message", "")}
    for f in d["failures"]
]

result = {
    "spec": "https://w3c.github.io/vc-di-ecdsa-test-suite/",
    "suite": "vc-di-ecdsa (ecdsa-rdfc-2019 + ecdsa-jcs-2019, P-256)",
    "runner": "tests/vc-di-ecdsa/run.sh",
    "retrieved_at": datetime.datetime.now(datetime.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"),
    "pass": stats["passes"],
    "fail": stats["failures"],
    "skip": stats.get("pending", 0),
    "total": stats["tests"],
    "present": True,
    "not_run_files": [
        "30-rdfc-interop.js", "60-sd-interop.js", "35-sd-di-create.js",
        "45-sd-di-verify.js", "90-algorithms-sd.js", "95-functions-sd.js",
    ],
    "not_run_reason": "interop tests are disabled (no other implementations offline); ecdsa-sd-2023 and P-384 are not configured",
    "failures": failures,
}

with open(out_path, "w") as f:
    json.dump(result, f, indent=2)
    f.write("\n")

print(f"vc-di-ecdsa: {stats['passes']} pass, {stats['failures']} fail (out of {stats['tests']}) -> {out_path}")
PYEOF
