#!/usr/bin/env python3
"""Write formal/lean4/L4Factoidal/JS/RyuTables.lean: the two 128-bit tables of Ryu
(Ulf Adams, "Ryu: fast float-to-string conversion", PLDI 2018), as pairs of UInt64
(low word first). Issue https://github.com/danbri/factoidal-core/issues/1076.

  invTable[i] = floor(2^(bitlen(5^i) - 1 + 125) / 5^i) + 1      for 0 <= i < 342
  powTable[i] = 5^i shifted to exactly 125 significant bits    for 0 <= i < 326

The Lean file checks each entry against these formulas with #guard.
Usage: python3 tools/gen-ryu-tables.py > formal/lean4/L4Factoidal/JS/RyuTables.lean
"""
M = (1 << 64) - 1

def inv(i):
    p = 5 ** i
    j = p.bit_length() - 1 + 125
    return (1 << j) // p + 1

def pw(i):
    p = 5 ** i
    s = p.bit_length() - 125
    return p >> s if s >= 0 else p << -s

def arr(name, doc, vals):
    out = [f"/-- {doc} -/", f"def {name} : Array UInt64 := #["]
    words = []
    for v in vals:
        assert v < (1 << 128)
        words += [v & M, v >> 64]
    lines = []
    for k in range(0, len(words), 4):
        lines.append("  " + ", ".join(f"0x{w:016X}" for w in words[k:k + 4]))
    out.append(",\n".join(lines))
    out.append("]")
    return "\n".join(out)

print("""/-!
# L4Factoidal.JS.RyuTables — the 128-bit tables of Ryū

Generated by `tools/gen-ryu-tables.py`; do not edit. Each entry is two words, low word first.
`L4Factoidal.JS.Ryu` checks every entry against its formula (`#guard`).
-/
namespace L4Factoidal.JS.Ryu
""")
print(arr("invTable", "`⌊2^(bitlen(5^i) - 1 + 125) / 5^i⌋ + 1` for `i < 342`.", [inv(i) for i in range(342)]))
print()
print(arr("powTable", "`5^i` shifted to 125 significant bits, for `i < 326`.", [pw(i) for i in range(326)]))
print()
print("end L4Factoidal.JS.Ryu")
