#!/usr/bin/env python3
"""Write the fuel-monotonicity lemmas of the large built-in dispatchers in parts (issue 531).

`Natives.moreNative` and `Natives.callNative` are each proved in K parts, one module and one Lean
process per part: part p is the lemma for the built-ins `id` with `nativePart id = p` (a round
robin over the constructors of `Native` and `NativeX`), and the walk closes every arm of the other
parts at once from that hypothesis. The whole lemma is put together by cases on `nativePart id`.

usage: fuelmono-natives-parts.py Value.lean OUTDIR K
"""
import re
import sys

src = open(sys.argv[1]).read()
out = sys.argv[2]
K = int(sys.argv[3])


def ctors(name):
    i = src.index(f'inductive {name} where')
    j = src.index('  deriving', i)
    body = re.sub(r'/--.*?-/', '', src[i:j], flags=re.S)
    body = re.sub(r'--[^\n]*', '', body)
    res = []
    for seg in body.split('|')[1:]:
        m = re.match(r'\s*(\w+)(.*)', seg, re.S)
        ar = sum(len(x.split()) for x in re.findall(r'\(([^():]+):', m.group(2)))
        res.append((m.group(1), ar))
    return res


N = ctors('Native')
X = ctors('NativeX')

w = []
w.append('import L4Factoidal.JS.FuelMonoNatives\nimport Lean.Elab.Tactic\n')
w.append('/-! Groups of built-ins, for the lemmas of `Natives.moreNative` and `Natives.callNative` in')
w.append(f'{K} parts (one Lean process each). Generated by `tools/fuelmono-natives-parts.py`. -/\n')
w.append('namespace L4Factoidal.JS.FuelMono\nopen L4Factoidal.JS\n')
w.append('/-- The part of a `NativeX` built-in. -/')
w.append('def nativePartX : NativeX → Nat')
for i, (c, a) in enumerate(X):
    w.append(f'  | .{c}' + ' _' * a + f' => {i % K}')
w.append('\n/-- The part of a built-in. -/')
w.append('def nativePart : Native → Nat')
j = 0
for c, a in N:
    if c == 'x':
        w.append('  | .x op => nativePartX op')
        continue
    w.append(f'  | .{c}' + ' _' * a + f' => {j % K}')
    j += 1
w.append(f'\ntheorem nativePart_lt (id : Native) : nativePart id < {K} := by')
w.append('  unfold nativePart')
w.append('  split <;> (try (unfold nativePartX; split)) <;> decide\n')
w.append('''open Lean Meta Elab Tactic in
/-- In a part of a built-in's lemma, an arm of another part: the hypothesis `nativePart id = p`
is false once `id` is a constructor (and, for `.x op`, `op` too). Checked only then: a `decide`
on `nativePart id` with `id` still a variable would unfold its match at every step. -/
elab "fuel_part_absurd" : tactic => do
  let g ← getMainGoal
  g.withContext do
    -- the part hypothesis is `hp` (the lemma's own name for it): one lookup, not a scan
    for d in ((← getLCtx).findFromUserName? `hp).toList do
      let t ← instantiateMVars d.type
      let some (_, lhs, _) := t.eq? | continue
      unless lhs.isAppOfArity ``nativePart 1 do continue
      let e := lhs.appArg!
      unless ← isConstructorApp e do continue
      if e.isAppOf ``Native.x then
        unless ← isConstructorApp e.appArg! do continue
      evalTactic (← `(tactic| exact absurd $(mkIdent d.userName) (by decide)))
      return
    throwError "fuel_part_absurd: no part hypothesis on a constructor"

macro_rules
  | `(tactic| fuel_mono_extra) => `(tactic| fuel_part_absurd)
''')
w.append('end L4Factoidal.JS.FuelMono')
open(f'{out}/FuelMonoNativeParts.lean', 'w').write('\n'.join(w) + '\n')

prev = 'L4Factoidal.JS.FuelMonoNativeParts'
for f in ['moreNative', 'callNative']:
    for p in range(K):
        mod = f'FuelMonoNatives_{f}_{p}'
        t = [f'import {prev}\n', f'/-! Fuel monotonicity of `Natives.{f}`, part {p} of {K} (`JS/FuelMonoNativeParts.lean`). -/\n',
             'namespace L4Factoidal.JS.FuelMono\nopen L4Factoidal.JS\n', 'variable {H : Type}\n',
             'set_option maxHeartbeats 0', 'set_option linter.unusedVariables false\n',
             f'theorem natives_{f}_mono_{p} {{c1 c2 : CoreFn H}} (hc : ∀ op, Le (c1 op) (c2 op))',
             f'    (id : Native) (hp : nativePart id = {p}) (thisV : Value) (args : Array Value) (nt : Option Value) :',
             f'    Le (Natives.{f} c1 id thisV args nt) (Natives.{f} c2 id thisV args nt) := by',
             f'  unfold Natives.{f}', '  fuel_walk\n', 'end L4Factoidal.JS.FuelMono']
        open(f'{out}/{mod}.lean', 'w').write('\n'.join(t) + '\n')
        prev = f'L4Factoidal.JS.{mod}'
    t = [f'import {prev}\n', f'/-! Fuel monotonicity of `Natives.{f}`, from its {K} parts. -/\n',
         'namespace L4Factoidal.JS.FuelMono\nopen L4Factoidal.JS\n', 'variable {H : Type}\n',
         f'theorem natives_{f}_mono {{c1 c2 : CoreFn H}} (hc : ∀ op, Le (c1 op) (c2 op))',
         '    (id : Native) (thisV : Value) (args : Array Value) (nt : Option Value) :',
         f'    Le (Natives.{f} c1 id thisV args nt) (Natives.{f} c2 id thisV args nt) := by',
         '  have hlt := nativePart_lt id',
         '  match h : nativePart id with']
    for p in range(K):
        t.append(f'  | {p} => exact natives_{f}_mono_{p} hc id h thisV args nt')
    t.append(f'  | _ + {K} => omega\n')
    t.append('end L4Factoidal.JS.FuelMono')
    open(f'{out}/FuelMonoNatives_{f}.lean', 'w').write('\n'.join(t) + '\n')
    prev = f'L4Factoidal.JS.FuelMonoNatives_{f}'
print('parts', K, 'natives', len(N), 'x', len(X))
