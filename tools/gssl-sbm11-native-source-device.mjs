// Device test fed exclusively by *native Lean* SBM11 PackSpec/toId? rows.
// The input is no longer a manually assigned JavaScript high-tag fixture.
// Test generates a temporary query lease; an authentic persisted generation
// manifest, production capture and a verified WGSL compiler remain open.
import {createSnapshotRequest} from "./gssl-sbm11-snapshot.mjs";
import {observeSnapshotBgp} from "./gssl-sbm11-snapshot-gpu.mjs";
import {compareExactRows,compareBags64} from "./gssl-sbm11-webgpu.mjs";

const [filename,headSha]=Deno.args;
if(!filename||!/^[0-9a-f]{40}$/.test(headSha??""))
  throw new Error("Usage: gssl-sbm11-native-source-device.mjs NATIVE.jsonl HEAD_SHA");
const records=(await Deno.readTextFile(filename)).trim().split("\n").map(JSON.parse);
if(records.length!==2||records.some(x=>x.kind!=="sbm11-pack-spec"))
  throw new Error("Expected two verified native Lean SBM11 PackSpec fixtures.");

const report={
  schema:"gssl-native-lean-sbm11-webgpu-v1",
  status:"fail",headSha,codebookAuthenticated:false,
  provenance:"SBM11 dictionary keys and TermIds generated by native Lean, independently of the GPU host",
  notes:"In-memory PackSpec dictionary, not activated persistent SBM11 generation",
  cases:[],
};
try{
  for(const source of records) {
    const triples=source.triples.map(row=>row.map(BigInt));
    const query={
      knows:BigInt(source.queryConstants.knows),
      works:BigInt(source.queryConstants.works),
      atlas:BigInt(source.queryConstants.atlas),
    };
    const expected=source.expected.map(row=>row.map(BigInt));
    const tags=new Set(triples.flat().map(id=>Number(id>>60n)));
    for(const tag of [1,2,3,9])
      if(!tags.has(tag))throw new Error("Missing real SBM11 dictionary term tag "+tag);
    const layouts=[];
    for(const layout of ["direct64Lanes","dense32Snapshot"]) {
      const request=await createSnapshotRequest({
        sourceId:"lean-native-pack-spec-fixture",
        generation:"in-memory-non-persistent-"+source.people,
        graphId:0n,
        codebookDigest:"e1".repeat(32), // do NOT claim a verified file-root digest
        queryText:"SELECT ?person ?colleague WHERE { ?person <urn:gssl:knows> ?colleague . ?colleague <urn:gssl:works> <urn:gssl:atlas> . }",
        requestNumber:1,layout,triples,queryConstants:query,
      });
      const actual=await observeSnapshotBgp(request,{current:()=>request.lease});
      if(actual.status!=="observed-not-certified")
        throw new Error(source.name+" "+layout+" refused: "+actual.reason);
      if(!compareExactRows(expected,actual.result.pairs)||
         !compareBags64(expected,actual.result.pairs))
        throw new Error(source.name+" "+layout+": WebGPU result differs from native Lean oracle.");
      layouts.push({
        layout,actualWebGPU:true,exactOrdered:true,exactBag:true,
        observedPairs:actual.result.pairs.length,
        adapter:actual.result.adapter,isFallbackAdapter:actual.result.isFallbackAdapter,
        dictionarySize:actual.result.dictionarySize??null,
      });
    }
    report.cases.push({name:source.name,people:source.people,
      triples:triples.length,dictionaryKeys:source.dictionaryKeys,
      sbm11Tags:[...tags].sort((a,b)=>a-b),nativePairs:expected.length,
      layouts});
  }
  report.status="pass";
}catch(e){
  report.error=e?.stack||String(e);
  Deno.exitCode=1;
}
console.log(JSON.stringify(report,null,2));
