#!/usr/bin/env python3
"""Generate formal/lean4/L4Factoidal/HTML/EntityData.lean from the WHATWG
named character reference table (https://html.spec.whatwg.org/entities.json).

    python3 tools/html/gen-entities.py entities.json > formal/lean4/L4Factoidal/HTML/EntityData.lean

Only the names with a trailing semicolon are written (2,125 names); the
legacy names without a semicolon are a subset handled by HTML.Entities.
"""
import json, sys
d = json.load(open(sys.argv[1]))
rows = sorted((k[1:-1], v['codepoints']) for k, v in d.items() if k.endswith(';'))
s = ';'.join(n + ':' + ' '.join(format(c, 'X') for c in cps) for n, cps in rows)
chunks = [s[i:i + 900] for i in range(0, len(s), 900)]
print('/-')
print('L4Factoidal.HTML.EntityData — generated by tools/html/gen-entities.py from the')
print('WHATWG HTML Living Standard named character references (entities.json,')
print('read 2026-10-28). Do not edit by hand.')
print('-/')
print('namespace L4Factoidal.HTML.EntityData')
print()
print('/-- `NAME:CP CP;...` for every name with a trailing semicolon (hex code points). -/')
print('def entityText : String := String.join [')
for i, c in enumerate(chunks):
    print('  "' + c + '"' + (',' if i + 1 < len(chunks) else ''))
print('  ]')
print()
print('end L4Factoidal.HTML.EntityData')
