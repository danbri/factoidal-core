#!/usr/bin/env python3
"""Generate formal/lean4/L4Factoidal/XPath4/RecordTypes.lean from the
fos:record-type elements of the F&O 4.0 function catalog.

Usage: python3 -I tools/xpath4/gen-record-types.py QTSPECS_DIR COMMIT > formal/lean4/L4Factoidal/XPath4/RecordTypes.lean

Rules (as in the earlier hand-made table): a field whose type allows the
empty sequence (it ends with ? or *) is optional (written "name"?), and a
function type is written fn(*) with the same occurrence indicator.
"""
import re, sys

def is_bare_fn(t):
    t = t.strip()
    return t.startswith('fn(') or t.startswith('function(')

def ftype(t):
    t = ' '.join(t.split())
    # an unparenthesized function type: a trailing ? or * is its result's
    if is_bare_fn(t):
        return 'fn(*)'
    occ = t[-1] if t and t[-1] in '?*+' else ''
    core = t[:-1] if occ else t
    c = core.strip()
    if c.startswith('(') and c.endswith(')'):
        inner = c[1:-1].strip()
        if inner.startswith('fn(') or inner.startswith('function('):
            return 'fn(*)' + occ
    if c.startswith('fn(') or c.startswith('function('):
        return 'fn(*)' + occ
    # an unprefixed named record type is an fn: name
    t = re.sub(r'(?<![:\w-])([a-z-]+-record)\b', r'fn:\1', t)
    return t

def main():
    root, commit = sys.argv[1], sys.argv[2]
    cat = open(root + '/specifications/xpath-functions-40/src/function-catalog.xml', encoding='utf-8').read()
    seen = set()
    rows = []
    for m in re.finditer(r'<fos:record-type id="([^"]+)"(.*?)</fos:record-type>', cat, re.S):
        name = m.group(1)
        if name in seen:
            continue
        seen.add(name)
        fs = []
        for fm in re.finditer(r'<fos:field name="([^"]+)"\s+type=("([^"]*)"|\'([^\']*)\')', m.group(2)):
            fname = fm.group(1)
            t = fm.group(3) if fm.group(3) is not None else fm.group(4)
            t = ' '.join(t.split())
            opt = (t.endswith('?') or t.endswith('*')) and not is_bare_fn(t)
            fs.append('\\"%s\\"%s as %s' % (fname, '?' if opt else '', ftype(t).replace('"', "'")))
        rows.append('  ("%s", "record(%s)")' % (name, ', '.join(fs)))
    print('''/-
L4Factoidal.XPath4.RecordTypes — the named record types of F&O 4.0
(`fn:dateTime-record`, `fn:uri-structure-record`, ...), as the source text
of an equivalent `record(...)` type.

Generated by `tools/xpath4/gen-record-types.py` from the `fos:record-type`
elements of `specifications/xpath-functions-40/src/function-catalog.xml` of
https://github.com/qt4cg/qtspecs at commit
%s. Two changes: a field whose type
allows the empty sequence is optional (`name?`, a marker that only this
text may use), and a field whose type is a function type is written
`fn(*)` (the record's function fields are matched, and coerced, as function
items of any signature).
-/
namespace L4Factoidal.XPath4

def recordTypesRaw : List (String × String) := [''' % commit)
    print(',\n'.join(rows))
    print(''']

end L4Factoidal.XPath4''')

main()
