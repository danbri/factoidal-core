#!/usr/bin/env python3
"""Generate formal/lean4/L4Factoidal/XPath4/UnicodeNormData.lean from the
Unicode Character Database (UCD) files UnicodeData.txt and
DerivedNormalizationProps.txt (Unicode 16.0.0,
https://www.unicode.org/Public/16.0.0/ucd/).

    python3 tools/xpath4/gen-unicode-norm.py UCD_DIR > formal/lean4/L4Factoidal/XPath4/UnicodeNormData.lean

The tables are written as string literals that the Lean module parses
once: the canonical combining classes, the FULL canonical and the full
compatibility decompositions (UAX #15 §1.3; Hangul syllables are left to
the algorithm of Unicode §3.12), and the primary composites (canonical
pairs that are not Full_Composition_Exclusion).
"""
import sys, os
d = sys.argv[1]
ccc = {}
dec = {}  # cp -> (compat, [cps])
for line in open(os.path.join(d, 'UnicodeData.txt'), encoding='utf-8'):
    f = line.rstrip('\n').split(';')
    cp = int(f[0], 16)
    if f[1].endswith('First>') or f[1].endswith('Last>'):
        continue
    if int(f[3]) != 0:
        ccc[cp] = int(f[3])
    if f[5]:
        parts = f[5].split()
        compat = parts[0].startswith('<')
        if compat:
            parts = parts[1:]
        dec[cp] = (compat, [int(x, 16) for x in parts])
excl = set()
for line in open(os.path.join(d, 'DerivedNormalizationProps.txt'), encoding='utf-8'):
    line = line.split('#')[0].strip()
    if not line:
        continue
    f = [x.strip() for x in line.split(';')]
    if len(f) >= 2 and f[1] == 'Full_Composition_Exclusion':
        r = f[0].split('..')
        a = int(r[0], 16); b = int(r[-1], 16)
        excl.update(range(a, b + 1))

def full(cp, compat):
    if cp not in dec:
        return [cp]
    c, xs = dec[cp]
    if c and not compat:
        return [cp]
    out = []
    for x in xs:
        out += full(x, compat)
    return out

canon = {cp: full(cp, False) for cp in dec if not dec[cp][0]}
compat = {}
for cp in dec:
    fc = full(cp, True)
    if canon.get(cp, [cp]) != fc:
        compat[cp] = fc
comp = []
for cp, (c, xs) in dec.items():
    if not c and len(xs) == 2 and cp not in excl:
        comp.append((xs[0], xs[1], cp))

def h(n): return format(n, 'X')
cccs = ';'.join(h(k) + ':' + str(v) for k, v in sorted(ccc.items()))
canons = ';'.join(h(k) + ':' + ' '.join(h(x) for x in v) for k, v in sorted(canon.items()))
compats = ';'.join(h(k) + ':' + ' '.join(h(x) for x in v) for k, v in sorted(compat.items()))
comps = ';'.join(h(a) + ' ' + h(b) + ':' + h(c) for a, b, c in sorted(comp))

def chunks(s, n=900):
    return [s[i:i + n] for i in range(0, len(s), n)]

def lit(name, s, doc):
    print('/-- ' + doc + ' -/')
    print('def ' + name + ' : String := String.join [')
    cs = chunks(s)
    for i, c in enumerate(cs):
        print('  "' + c + '"' + (',' if i + 1 < len(cs) else ''))
    print('  ]')
    print()

print('/-')
print('L4Factoidal.XPath4.UnicodeNormData — generated by tools/xpath4/gen-unicode-norm.py')
print('from the Unicode Character Database 16.0.0 (UnicodeData.txt,')
print('DerivedNormalizationProps.txt). Do not edit by hand.')
print('-/')
print('namespace L4Factoidal.XPath4.UnicodeNormData')
print()
lit('cccText', cccs, 'Canonical_Combining_Class values other than 0: `CP:CLASS;...` (hex code point).')
lit('canonText', canons, 'Full canonical decompositions: `CP:CP CP ...;...`.')
lit('compatText', compats, 'Full compatibility decompositions that differ from the canonical ones.')
lit('compText', comps, 'Primary composites: `FIRST SECOND:COMPOSITE;...`.')
print('end L4Factoidal.XPath4.UnicodeNormData')
