#!/usr/bin/env python3
"""Generate formal/lean4/L4Factoidal/Regex/UnicodeProps.lean from the Unicode
Character Database 16.0.0 (https://www.unicode.org/Public/16.0.0/ucd/):
UnicodeData.txt (General_Category) and Blocks.txt.

    python3 -I tools/xpath4/gen-regex-props.py UNICODEDATA BLOCKS \
        > formal/lean4/L4Factoidal/Regex/UnicodeProps.lean

The tables serve the XSD 1.1 Part 2 Appendix G category escapes `\\p{X}`
(G.4.2.2) and block escapes `\\p{IsX}` (G.4.2.3) of the F&O 4.0 regular
expression dialect (F&O 4.0 section 6.1).

* `catText`: one line per two-letter General_Category value except Cs, as
  `Xx:lo-hi lo-hi ...` (hex, inclusive, sorted, merged). Cn is every code
  point in 0..10FFFF that UnicodeData.txt does not list.
* `blockText`: one line per block, `NormalizedName:lo-hi`, where the
  normalized block name strips white space and underbars (G.4.2.3), plus
  the Unicode 3.1 names that G.4.2.3 lists as superseded (Greek,
  CombiningMarksforSymbols, PrivateUse).
"""
import sys

def merge(rs):
    rs = sorted(rs)
    out = []
    for a, b in rs:
        if out and a <= out[-1][1] + 1:
            out[-1][1] = max(out[-1][1], b)
        else:
            out.append([a, b])
    return out

cats = {}
assigned = []
first = None
for line in open(sys.argv[1], encoding='utf-8'):
    f = line.rstrip('\n').split(';')
    cp = int(f[0], 16)
    gc = f[2]
    if f[1].endswith(', First>'):
        first = cp
        continue
    lo = cp
    if f[1].endswith(', Last>'):
        lo = first
        first = None
    assigned.append((lo, cp))
    cats.setdefault(gc, []).append((lo, cp))

assigned = merge(assigned)
cn = []
nxt = 0
for a, b in assigned:
    if a > nxt:
        cn.append((nxt, a - 1))
    nxt = b + 1
if nxt <= 0x10FFFF:
    cn.append((nxt, 0x10FFFF))
cats['Cn'] = cn
cats.pop('Cs', None)

blocks = []
for line in open(sys.argv[2], encoding='utf-8'):
    line = line.split('#')[0].strip()
    if not line:
        continue
    rng, name = [x.strip() for x in line.split(';')]
    a, b = rng.split('..')
    norm = ''.join(ch for ch in name if not ch.isspace() and ch != '_')
    blocks.append((norm, [(int(a, 16), int(b, 16))]))
names = {n for n, _ in blocks}
for n, rs in [('Greek', [(0x370, 0x3FF)]),
              ('CombiningMarksforSymbols', [(0x20D0, 0x20FF)]),
              ('PrivateUse', [(0xE000, 0xF8FF), (0xF0000, 0xFFFFD), (0x100000, 0x10FFFD)])]:
    if n not in names:
        blocks.append((n, rs))

def fmt(rs):
    return ' '.join('%X-%X' % (a, b) for a, b in rs)

def lean_str_lines(lines):
    return '\n'.join('  "%s\\n"%s' % (l, ',' if i + 1 < len(lines) else '') for i, l in enumerate(lines))

cat_lines = ['%s:%s' % (k, fmt(merge(v))) for k, v in sorted(cats.items())]
block_lines = ['%s:%s' % (n, fmt(rs)) for n, rs in blocks]

print('''/-
L4Factoidal.Regex.UnicodeProps — generated by tools/xpath4/gen-regex-props.py
from the Unicode Character Database 16.0.0 (UnicodeData.txt, Blocks.txt).
Do not edit by hand.
-/
namespace L4Factoidal.Regex.UnicodeProps

/-- Unicode version of the tables. -/
def unicodeVersion : String := "16.0.0"

/-- General_Category values (two letters, Cs excluded, Cn computed):
`Xx:lo-hi lo-hi ...` per line, hex, inclusive, sorted and merged. -/
def catText : String := String.join [
%s
  ]

/-- Blocks by normalized block name (XSD 1.1 Part 2 G.4.2.3), and the
superseded Unicode 3.1 names: `Name:lo-hi ...` per line. -/
def blockText : String := String.join [
%s
  ]

end L4Factoidal.Regex.UnicodeProps''' % (lean_str_lines(cat_lines), lean_str_lines(block_lines)))
