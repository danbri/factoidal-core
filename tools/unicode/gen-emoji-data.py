#!/usr/bin/env python3
"""Generate formal/lean4/L4Factoidal/Unicode/EmojiData.lean from the vendored
Unicode 18.0.0 emoji-data.txt (UTS #51): the properties that choose between the
emoji (colour) and text presentation of a character and that make emoji sequences.

    python3 tools/unicode/gen-emoji-data.py          rewrite the module
    python3 tools/unicode/gen-emoji-data.py --check  exit 1 if it differs

One RangeTable text `lo hi v;...` (hex, hex, decimal) whose value is a set of bits:
1 Emoji_Presentation, 2 Emoji_Modifier, 4 Emoji_Modifier_Base, 8 Emoji_Component,
16 Emoji. A code point with none of them is not listed.
"""
import sys, os
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, '..', '..'))
UCD = os.path.join(ROOT, 'third_party', 'unicode-18.0.0')
OUT = os.path.join(ROOT, 'formal', 'lean4', 'L4Factoidal', 'Unicode', 'EmojiData.lean')
BITS = {'Emoji_Presentation': 1, 'Emoji_Modifier': 2, 'Emoji_Modifier_Base': 4,
        'Emoji_Component': 8, 'Emoji': 16}

m = {}
for line in open(os.path.join(UCD, 'emoji-data.txt'), encoding='utf-8'):
    line = line.split('#')[0].strip()
    if not line:
        continue
    f = [x.strip() for x in line.split(';')]
    if f[1] not in BITS:
        continue
    r = f[0].split('..')
    for cp in range(int(r[0], 16), int(r[-1], 16) + 1):
        m[cp] = m.get(cp, 0) | BITS[f[1]]

out = []
for k in sorted(m):
    v = m[k]
    if out and out[-1][1] + 1 == k and out[-1][2] == v:
        out[-1][1] = k
    else:
        out.append([k, k, v])
s = ';'.join('%X %X %d' % (a, b, v) for a, b, v in out)
chunks = [s[i:i + 900] for i in range(0, len(s), 900)]
parts = [
    '/-',
    'L4Factoidal.Unicode.EmojiData — generated by tools/unicode/gen-emoji-data.py',
    'from emoji-data.txt of Unicode 18.0.0 (UTS #51). Do not edit by hand.',
    '-/',
    'namespace L4Factoidal.Unicode.EmojiData',
    '',
    'def presentation : UInt8 := 1',
    'def modifier : UInt8 := 2',
    'def modifierBase : UInt8 := 4',
    'def component : UInt8 := 8',
    'def emoji : UInt8 := 16',
    '',
    '/-- Emoji properties as bits (`presentation`, `modifier`, `modifierBase`, `component`, `emoji`). -/',
    'def emojiText : String := String.join [']
for i, c in enumerate(chunks):
    parts.append('  "' + c + '"' + (',' if i + 1 < len(chunks) else ''))
parts += ['  ]', '', 'end L4Factoidal.Unicode.EmojiData', '']
text = '\n'.join(parts)
if '--check' in sys.argv:
    cur = open(OUT, encoding='utf-8').read() if os.path.exists(OUT) else None
    if cur != text:
        sys.stderr.write('gen-emoji-data: %s is out of date\n' % OUT)
        sys.exit(1)
    sys.exit(0)
open(OUT, 'w', encoding='utf-8').write(text)
