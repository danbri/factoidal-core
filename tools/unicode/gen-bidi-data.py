#!/usr/bin/env python3
"""Generate formal/lean4/L4Factoidal/Unicode/BidiData.lean from the Unicode
18.0.0 UCD files (https://github.com/danbri/factoidal/issues/1167, milestone 4).

Inputs (third_party/unicode-18.0.0/):
  DerivedBidiClass.txt  Bidi_Class, with the @missing default values for
                        unassigned code points applied first, in file order.
  BidiBrackets.txt      Bidi_Paired_Bracket, Bidi_Paired_Bracket_Type.
  BidiMirroring.txt     Bidi_Mirroring_Glyph.
  UnicodeData.txt       singleton canonical decompositions, for the canonical
                        equivalents of paired brackets (UAX #9 BD16).

  gen-bidi-data.py          rewrite the Lean module
  gen-bidi-data.py --check  exit 1 if the committed module differs
"""
import os
import re
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
UCD = os.path.join(ROOT, "third_party", "unicode-18.0.0")
OUT = os.path.join(ROOT, "formal", "lean4", "L4Factoidal", "Unicode", "BidiData.lean")

# Order of the constructors of `L4Factoidal.Unicode.BidiClass`.
CLASSES = ["L", "R", "AL", "EN", "ES", "ET", "AN", "CS", "NSM", "BN", "B", "S",
           "WS", "ON", "LRE", "LRO", "RLE", "RLO", "PDF", "LRI", "RLI", "FSI", "PDI"]
LONG = {
    "Left_To_Right": "L", "Right_To_Left": "R", "Arabic_Letter": "AL",
    "European_Number": "EN", "European_Separator": "ES", "European_Terminator": "ET",
    "Arabic_Number": "AN", "Common_Separator": "CS", "Nonspacing_Mark": "NSM",
    "Boundary_Neutral": "BN", "Paragraph_Separator": "B", "Segment_Separator": "S",
    "White_Space": "WS", "Other_Neutral": "ON", "Left_To_Right_Embedding": "LRE",
    "Left_To_Right_Override": "LRO", "Right_To_Left_Embedding": "RLE",
    "Right_To_Left_Override": "RLO", "Pop_Directional_Format": "PDF",
    "Left_To_Right_Isolate": "LRI", "Right_To_Left_Isolate": "RLI",
    "First_Strong_Isolate": "FSI", "Pop_Directional_Isolate": "PDI",
}


def rng(s):
    s = s.strip()
    if ".." in s:
        a, b = s.split("..")
        return int(a, 16), int(b, 16)
    return int(s, 16), int(s, 16)


def bidi_classes():
    vals = bytearray(0x110000)  # 0 = L
    explicit = []
    with open(os.path.join(UCD, "DerivedBidiClass.txt"), encoding="utf-8") as f:
        for line in f:
            m = re.match(r"#\s*@missing:\s*([0-9A-Fa-f.]+)\s*;\s*(\w+)", line)
            if m:
                lo, hi = rng(m.group(1))
                v = CLASSES.index(LONG[m.group(2)])
                for c in range(lo, hi + 1):
                    vals[c] = v
                continue
            line = line.split("#", 1)[0].strip()
            if not line:
                continue
            r, cls = [x.strip() for x in line.split(";")]
            explicit.append((rng(r), CLASSES.index(cls)))
    for (lo, hi), v in explicit:
        for c in range(lo, hi + 1):
            vals[c] = v
    out = []
    lo = 0
    for c in range(1, 0x110001):
        if c == 0x110000 or vals[c] != vals[lo]:
            if vals[lo] != 0:
                out.append("%X %X %d" % (lo, c - 1, vals[lo]))
            lo = c
    return ";".join(out)


def canonical_singletons():
    canon = {}
    with open(os.path.join(UCD, "UnicodeData.txt"), encoding="utf-8") as f:
        for line in f:
            fs = line.split(";")
            d = fs[5].strip()
            if d and not d.startswith("<") and " " not in d:
                canon[int(fs[0], 16)] = int(d, 16)
    return canon


def brackets():
    canon = canonical_singletons()
    out = []
    with open(os.path.join(UCD, "BidiBrackets.txt"), encoding="utf-8") as f:
        for line in f:
            line = line.split("#", 1)[0].strip()
            if not line:
                continue
            cp, pair, t = [x.strip() for x in line.split(";")]
            cp, pair = int(cp, 16), int(pair, 16)
            kind = 1 if t == "o" else 2
            # Field 2: the canonical equivalent of the paired bracket (pushed by
            # an opening bracket); field 4: the canonical equivalent of the
            # character itself (compared by a closing bracket).
            out.append("%X %X %d %X" % (cp, canon.get(pair, pair), kind, canon.get(cp, cp)))
    return ";".join(out)


def mirrors():
    out = []
    with open(os.path.join(UCD, "BidiMirroring.txt"), encoding="utf-8") as f:
        for line in f:
            line = line.split("#", 1)[0].strip()
            if not line:
                continue
            a, b = [x.strip() for x in line.split(";")]
            out.append("%X %X" % (int(a, 16), int(b, 16)))
    return ";".join(out)


def render():
    return f'''/-
L4Factoidal.Unicode.BidiData — the character properties of the Unicode
Bidirectional Algorithm (UAX #9, revision 52), Unicode 18.0.0
(https://github.com/danbri/factoidal/issues/1167, milestone 4).

GENERATED by tools/unicode/gen-bidi-data.py; do not edit. Sources, all
Unicode 18.0.0 (third_party/unicode-18.0.0/):

  DerivedBidiClass.txt  Bidi_Class (UAX #9 §3.2), with the @missing default
                        values for unassigned code points.
  BidiBrackets.txt      Bidi_Paired_Bracket and Bidi_Paired_Bracket_Type
                        (UAX #9 BD14, BD15).
  UnicodeData.txt       singleton canonical decompositions, for the canonical
                        equivalents of paired brackets (UAX #9 BD16).
  BidiMirroring.txt     Bidi_Mirroring_Glyph (UAX #9 §7).

`bidiClassText` is `lo hi v;...` (hex, hex, decimal), read by
`RangeTable.ofText`; `v` is the constructor index of
`L4Factoidal.Unicode.BidiClass` (default 0 = L).
`bracketText` is `cp pairCanon type selfCanon;...` (type 1 = open,
2 = close). `mirrorText` is `cp glyph;...`.
-/
import L4Factoidal.Unicode.RangeTable

namespace L4Factoidal.Unicode.BidiData

def bidiClassText : String := "{bidi_classes()}"

def bidiClassTable : RangeTable := RangeTable.ofText bidiClassText 0

def bracketText : String := "{brackets()}"

def mirrorText : String := "{mirrors()}"

#guard bidiClassTable.get 0x41 == 0
#guard bidiClassTable.get 0x5D0 == 1
#guard bidiClassTable.get 0x627 == 2
#guard bidiClassTable.get 0x5FF == 1
#guard bidiClassTable.get 0x20CF == 5

end L4Factoidal.Unicode.BidiData
'''


def main():
    text = render()
    if len(sys.argv) > 1 and sys.argv[1] == "--check":
        try:
            with open(OUT, encoding="utf-8") as f:
                cur = f.read()
        except FileNotFoundError:
            cur = None
        if cur != text:
            print("gen-bidi-data.py: %s is out of date" % os.path.relpath(OUT, ROOT), file=sys.stderr)
            sys.exit(1)
        sys.exit(0)
    with open(OUT, "w", encoding="utf-8") as f:
        f.write(text)


if __name__ == "__main__":
    main()
