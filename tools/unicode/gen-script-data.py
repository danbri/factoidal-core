#!/usr/bin/env python3
"""Generate formal/lean4/L4Factoidal/Unicode/ScriptData.lean from the vendored
Unicode 18.0.0 files in third_party/unicode-18.0.0: Scripts.txt (the Script
property) and PropertyValueAliases.txt (its ISO 15924 short names).

    python3 tools/unicode/gen-script-data.py          rewrite the module
    python3 tools/unicode/gen-script-data.py --check  exit 1 if it differs

The table is one RangeTable text `lo hi v;...` (hex, hex, decimal); `v` is
an index into `codes`, with 0 = Zzzz (Unknown), the default, not listed.
"""
import sys, os
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, '..', '..'))
UCD = os.path.join(ROOT, 'third_party', 'unicode-18.0.0')
OUT = os.path.join(ROOT, 'formal', 'lean4', 'L4Factoidal', 'Unicode', 'ScriptData.lean')

short = {}
for line in open(os.path.join(UCD, 'PropertyValueAliases.txt'), encoding='utf-8'):
    line = line.split('#')[0].strip()
    f = [x.strip() for x in line.split(';')]
    if len(f) >= 3 and f[0] == 'sc':
        short[f[2]] = f[1]
codes = ['Zzzz'] + sorted(set(short.values()) - {'Zzzz'})
if len(codes) > 255:
    raise SystemExit('more than 255 scripts')
m = {}
for line in open(os.path.join(UCD, 'Scripts.txt'), encoding='utf-8'):
    line = line.split('#')[0].strip()
    if not line:
        continue
    f = [x.strip() for x in line.split(';')]
    if f[1] not in short:
        raise SystemExit('Scripts.txt: unknown script %r' % f[1])
    r = f[0].split('..')
    for cp in range(int(r[0], 16), int(r[-1], 16) + 1):
        m[cp] = codes.index(short[f[1]])
out = []
for cp in sorted(m):
    v = m[cp]
    if v == 0:
        continue
    if out and out[-1][1] == cp - 1 and out[-1][2] == v:
        out[-1][1] = cp
    else:
        out.append([cp, cp, v])
text = ';'.join('%X %X %d' % (a, b, v) for a, b, v in out)
src = '\n'.join([
    '/-',
    'L4Factoidal.Unicode.ScriptData — generated by tools/unicode/gen-script-data.py',
    'from the Unicode Character Database 18.0.0: Scripts.txt and',
    'PropertyValueAliases.txt. Do not edit by hand. `table` is RangeTable text',
    '`lo hi v;...`; `v` indexes `codes` (ISO 15924), 0 = Zzzz (Unknown).',
    '-/',
    'import L4Factoidal.Unicode.RangeTable',
    '',
    'namespace L4Factoidal.Unicode.ScriptData',
    '',
    'def codes : Array String := #[' + ', '.join('"%s"' % c for c in codes) + ']',
    '',
    'def tableText : String := "' + text + '"',
    '',
    'def table : RangeTable := RangeTable.ofText tableText',
    '',
    '/-- ISO 15924 code of the Script property of `c`. -/',
    'def scriptOf (c : Nat) : String := codes.getD (table.get c.toUInt32).toNat "Zzzz"',
    '',
    '#guard scriptOf 0x41 == "Latn"',
    '#guard scriptOf 0x1BC36 == "Dupl"',
    '#guard scriptOf 0x30 == "Zyyy"',
    '#guard scriptOf 0x301 == "Zinh"',
    '',
    'end L4Factoidal.Unicode.ScriptData',
    ''])
if '--check' in sys.argv:
    cur = open(OUT, encoding='utf-8').read() if os.path.exists(OUT) else None
    sys.exit(0 if cur == src else 1)
open(OUT, 'w', encoding='utf-8').write(src)
print('%d scripts, %d ranges' % (len(codes), len(out)))
