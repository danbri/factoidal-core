#!/usr/bin/env python3
"""Generate formal/lean4/L4Factoidal/Unicode/SegmentData.lean from the vendored
Unicode 18.0.0 files in third_party/unicode-18.0.0: GraphemeBreakProperty.txt,
WordBreakProperty.txt, SentenceBreakProperty.txt, emoji-data.txt
(Extended_Pictographic) and DerivedCoreProperties.txt (Indic_Conjunct_Break),
the data of UAX #29 (text segmentation).

    python3 tools/unicode/gen-segment-data.py          rewrite the module
    python3 tools/unicode/gen-segment-data.py --check  exit 1 if it differs

Each table is one RangeTable text `lo hi v;...` (hex, hex, decimal). The
value numbers are the order of the name lists below, with 0 = the default
value (Other, None, No); the module also defines one constant per name.
"""
import sys, os
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, '..', '..'))
UCD = os.path.join(ROOT, 'third_party', 'unicode-18.0.0')
OUT = os.path.join(ROOT, 'formal', 'lean4', 'L4Factoidal', 'Unicode', 'SegmentData.lean')

GCB = ['Other', 'CR', 'LF', 'Control', 'Extend', 'ZWJ', 'Regional_Indicator',
       'Prepend', 'SpacingMark', 'L', 'V', 'T', 'LV', 'LVT']
WB = ['Other', 'CR', 'LF', 'Newline', 'Extend', 'ZWJ', 'Regional_Indicator',
      'Format', 'Katakana', 'Hebrew_Letter', 'ALetter', 'Single_Quote',
      'Double_Quote', 'MidNumLet', 'MidLetter', 'MidNum', 'Numeric',
      'ExtendNumLet', 'WSegSpace']
SB = ['Other', 'CR', 'LF', 'Extend', 'Sep', 'Format', 'Sp', 'Lower', 'Upper',
      'OLetter', 'Numeric', 'ATerm', 'SContinue', 'STerm', 'Close']
INCB = ['None', 'Linker', 'Consonant', 'Extend']
EXTPICT = ['No', 'Yes']


def read(fname, prop, names):
    """Map code point -> value index from lines `A..B ; Value # ...`."""
    m = {}
    for line in open(os.path.join(UCD, fname), encoding='utf-8'):
        line = line.split('#')[0].strip()
        if not line:
            continue
        f = [x.strip() for x in line.split(';')]
        if prop is None:
            if len(f) < 2:
                continue
            v = f[1]
        else:
            if len(f) < 2 or f[1] != prop:
                continue
            v = f[2] if len(f) > 2 else 'Yes'  # emoji-data.txt lists only the 'Yes' ranges
        if v not in names:
            raise SystemExit('%s: unknown value %r' % (fname, v))
        r = f[0].split('..')
        a = int(r[0], 16)
        b = int(r[-1], 16)
        for cp in range(a, b + 1):
            m[cp] = names.index(v)
    return m


def ranges(m):
    out = []
    for k in sorted(m):
        v = m[k]
        if v == 0:
            continue
        if out and out[-1][1] + 1 == k and out[-1][2] == v:
            out[-1][1] = k
        else:
            out.append([k, k, v])
    return ';'.join('%X %X %d' % (a, b, v) for a, b, v in out)


def lit(name, s, doc):
    o = ['/-- ' + doc + ' -/', 'def ' + name + ' : String := String.join [']
    cs = [s[i:i + 900] for i in range(0, len(s), 900)]
    for i, c in enumerate(cs):
        o.append('  "' + c + '"' + (',' if i + 1 < len(cs) else ''))
    o.append('  ]')
    o.append('')
    return '\n'.join(o)


def consts(ns, names):
    o = ['namespace ' + ns]
    for i, n in enumerate(names):
        o.append('def %s : UInt8 := %d' % (n, i))
    o.append('end ' + ns)
    o.append('')
    return '\n'.join(o)


gcb = read('GraphemeBreakProperty.txt', None, GCB)
wb = read('WordBreakProperty.txt', None, WB)
sb = read('SentenceBreakProperty.txt', None, SB)
incb = read('DerivedCoreProperties.txt', 'InCB', INCB)
ext = read('emoji-data.txt', 'Extended_Pictographic', EXTPICT)

parts = [
    '/-',
    'L4Factoidal.Unicode.SegmentData — generated by tools/unicode/gen-segment-data.py',
    'from the Unicode Character Database 18.0.0: GraphemeBreakProperty.txt,',
    'WordBreakProperty.txt, SentenceBreakProperty.txt, emoji-data.txt',
    '(Extended_Pictographic) and DerivedCoreProperties.txt (Indic_Conjunct_Break).',
    'Do not edit by hand. Each table is RangeTable text `lo hi v;...`; the value 0',
    'is the default (Other, None, No) and is not listed.',
    '-/',
    'namespace L4Factoidal.Unicode.SegmentData',
    '',
    consts('GCB', GCB),
    consts('WB', WB),
    consts('SB', SB),
    consts('InCB', INCB),
    lit('gcbText', ranges(gcb), 'Grapheme_Cluster_Break (values of `GCB`).'),
    lit('wbText', ranges(wb), 'Word_Break (values of `WB`).'),
    lit('sbText', ranges(sb), 'Sentence_Break (values of `SB`).'),
    lit('incbText', ranges(incb), 'Indic_Conjunct_Break (values of `InCB`).'),
    lit('extPictText', ranges(ext), 'Extended_Pictographic (1 = Yes).'),
    'end L4Factoidal.Unicode.SegmentData',
    '']
text = '\n'.join(parts)
if '--check' in sys.argv:
    cur = open(OUT, encoding='utf-8').read() if os.path.exists(OUT) else None
    if cur != text:
        sys.stderr.write('gen-segment-data: %s is out of date\n' % OUT)
        sys.exit(1)
    sys.exit(0)
open(OUT, 'w', encoding='utf-8').write(text)
