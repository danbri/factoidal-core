#!/usr/bin/env python3
"""Generate formal/lean4/L4Factoidal/Unicode/JoiningData.lean from the vendored
Unicode 18.0.0 files in third_party/unicode-18.0.0: ArabicShaping.txt (Joining_Type
and Joining_Group) and DerivedGeneralCategory.txt.

    python3 tools/unicode/gen-joining-data.py          rewrite the module
    python3 tools/unicode/gen-joining-data.py --check  exit 1 if it differs

The values are the columns of the joining state machine of the Arabic shaper
(HarfBuzz hb-ot-shaper-arabic.cc, `get_joining_type`, 15.0.0):

    0 U (Non_Joining), 1 L (Left_Joining), 2 R (Right_Joining),
    3 D (Dual_Joining; Join_Causing C is the same column),
    4 R with Joining_Group ALAPH, 5 R with Joining_Group DALATH RISH,
    6 T (Transparent).

A code point that ArabicShaping.txt does not list is T when its General_Category
is Mn, Me or Cf, and U otherwise, as in HarfBuzz. U is the default, not listed.
"""
import sys, os
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, '..', '..'))
UCD = os.path.join(ROOT, 'third_party', 'unicode-18.0.0')
OUT = os.path.join(ROOT, 'formal', 'lean4', 'L4Factoidal', 'Unicode', 'JoiningData.lean')

def ranges(path):
    for line in open(os.path.join(UCD, path), encoding='utf-8'):
        line = line.split('#')[0].strip()
        if not line:
            continue
        f = [x.strip() for x in line.split(';')]
        r = f[0].split('..')
        yield int(r[0], 16), int(r[-1], 16), f

col = {'U': 0, 'L': 1, 'R': 2, 'D': 3, 'C': 3, 'T': 6}
m = {}
for lo, hi, f in ranges('DerivedGeneralCategory.txt'):
    if f[1] in ('Mn', 'Me', 'Cf'):
        for cp in range(lo, hi + 1):
            m[cp] = 6
for lo, hi, f in ranges('ArabicShaping.txt'):
    v = col[f[2]]
    if f[3] == 'ALAPH':
        v = 4
    elif f[3] == 'DALATH RISH':
        v = 5
    for cp in range(lo, hi + 1):
        m[cp] = v
out = []
for cp in sorted(m):
    v = m[cp]
    if v == 0:
        continue
    if out and out[-1][1] == cp - 1 and out[-1][2] == v:
        out[-1][1] = cp
    else:
        out.append([cp, cp, v])
text = ';'.join('%X %X %d' % (a, b, v) for a, b, v in out)
src = '\n'.join([
    '/-',
    'L4Factoidal.Unicode.JoiningData — generated by tools/unicode/gen-joining-data.py',
    'from the Unicode Character Database 18.0.0: ArabicShaping.txt and',
    'DerivedGeneralCategory.txt. Do not edit by hand. `table` is RangeTable text',
    '`lo hi v;...`; `v` is a column of the joining state machine of the Arabic',
    'shaper (HarfBuzz `get_joining_type`): 0 U, 1 L, 2 R, 3 D or C, 4 ALAPH,',
    '5 DALATH RISH, 6 T. A code point not in ArabicShaping.txt is T for',
    'General_Category Mn, Me and Cf, else U (the default).',
    '-/',
    'import L4Factoidal.Unicode.RangeTable',
    '',
    'namespace L4Factoidal.Unicode.JoiningData',
    '',
    'def tableText : String := "' + text + '"',
    '',
    'def table : RangeTable := RangeTable.ofText tableText',
    '',
    '/-- The joining column of `c` (see the module comment). -/',
    'def joiningOf (c : Nat) : Nat := (table.get c.toUInt32).toNat',
    '',
    '#guard joiningOf 0x0627 == 2',
    '#guard joiningOf 0x0628 == 3',
    '#guard joiningOf 0x200D == 3',
    '#guard joiningOf 0x200C == 0',
    '#guard joiningOf 0x064E == 6',
    '#guard joiningOf 0x0710 == 4',
    '#guard joiningOf 0x072A == 5',
    '#guard joiningOf 0x0041 == 0',
    '',
    'end L4Factoidal.Unicode.JoiningData',
    ''])
if '--check' in sys.argv:
    cur = open(OUT, encoding='utf-8').read() if os.path.exists(OUT) else None
    sys.exit(0 if cur == src else 1)
open(OUT, 'w', encoding='utf-8').write(src)
print('%d ranges' % len(out))
