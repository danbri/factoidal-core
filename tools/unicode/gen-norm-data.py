#!/usr/bin/env python3
"""Generate formal/lean4/L4Factoidal/Unicode/NormData.lean from the vendored
Unicode 18.0.0 files third_party/unicode-18.0.0/UnicodeData.txt and
DerivedNormalizationProps.txt (https://www.unicode.org/Public/18.0.0/ucd/).

    python3 tools/unicode/gen-norm-data.py          rewrite the module
    python3 tools/unicode/gen-norm-data.py --check  exit 1 if it differs

Tables (UAX #15 §1.3, Unicode §3.11 and §3.12): Canonical_Combining_Class
(a RangeTable text), the full canonical decompositions, the full
compatibility decompositions that differ from the canonical ones, and the
primary composites (canonical pairs that are not Full_Composition_Exclusion).
Hangul syllables are left to the arithmetic of Unicode §3.12.
"""
import sys, os
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, '..', '..'))
UCD = os.path.join(ROOT, 'third_party', 'unicode-18.0.0')
OUT = os.path.join(ROOT, 'formal', 'lean4', 'L4Factoidal', 'Unicode', 'NormData.lean')

ccc = {}
dec = {}
for line in open(os.path.join(UCD, 'UnicodeData.txt'), encoding='utf-8'):
    f = line.rstrip('\n').split(';')
    cp = int(f[0], 16)
    if f[1].endswith('First>') or f[1].endswith('Last>'):
        continue
    if int(f[3]) != 0:
        ccc[cp] = int(f[3])
    if f[5]:
        parts = f[5].split()
        compat = parts[0].startswith('<')
        if compat:
            parts = parts[1:]
        dec[cp] = (compat, [int(x, 16) for x in parts])
excl = set()
for line in open(os.path.join(UCD, 'DerivedNormalizationProps.txt'), encoding='utf-8'):
    line = line.split('#')[0].strip()
    if not line:
        continue
    f = [x.strip() for x in line.split(';')]
    if len(f) >= 2 and f[1] == 'Full_Composition_Exclusion':
        r = f[0].split('..')
        excl.update(range(int(r[0], 16), int(r[-1], 16) + 1))


def full(cp, compat):
    if cp not in dec:
        return [cp]
    c, xs = dec[cp]
    if c and not compat:
        return [cp]
    out = []
    for x in xs:
        out += full(x, compat)
    return out


canon = {cp: full(cp, False) for cp in dec if not dec[cp][0]}
compat = {}
for cp in dec:
    fc = full(cp, True)
    if canon.get(cp, [cp]) != fc:
        compat[cp] = fc
comp = [(xs[0], xs[1], cp) for cp, (c, xs) in dec.items()
        if not c and len(xs) == 2 and cp not in excl]


def h(n):
    return format(n, 'X')


def ranges(m):
    out = []
    for k in sorted(m):
        v = m[k]
        if out and out[-1][1] + 1 == k and out[-1][2] == v:
            out[-1][1] = k
        else:
            out.append([k, k, v])
    return ';'.join('%s %s %d' % (h(a), h(b), v) for a, b, v in out)


cccs = ranges(ccc)
canons = ';'.join(h(k) + ':' + ' '.join(h(x) for x in v) for k, v in sorted(canon.items()))
compats = ';'.join(h(k) + ':' + ' '.join(h(x) for x in v) for k, v in sorted(compat.items()))
comps = ';'.join(h(a) + ' ' + h(b) + ':' + h(c) for a, b, c in sorted(comp))


def lit(name, s, doc):
    o = ['/-- ' + doc + ' -/', 'def ' + name + ' : String := String.join [']
    cs = [s[i:i + 900] for i in range(0, len(s), 900)]
    for i, c in enumerate(cs):
        o.append('  "' + c + '"' + (',' if i + 1 < len(cs) else ''))
    o.append('  ]')
    o.append('')
    return '\n'.join(o)


parts = [
    '/-',
    'L4Factoidal.Unicode.NormData — generated by tools/unicode/gen-norm-data.py',
    'from the Unicode Character Database 18.0.0 (UnicodeData.txt,',
    'DerivedNormalizationProps.txt). Do not edit by hand.',
    '-/',
    'namespace L4Factoidal.Unicode.NormData',
    '',
    lit('cccText', cccs, 'Canonical_Combining_Class values other than 0, as RangeTable text `lo hi v;...`.'),
    lit('canonText', canons, 'Full canonical decompositions: `CP:CP CP ...;...` (hex).'),
    lit('compatText', compats, 'Full compatibility decompositions that differ from the canonical ones.'),
    lit('compText', comps, 'Primary composites: `FIRST SECOND:COMPOSITE;...`.'),
    'end L4Factoidal.Unicode.NormData',
    '']
text = '\n'.join(parts)
if '--check' in sys.argv:
    cur = open(OUT, encoding='utf-8').read() if os.path.exists(OUT) else None
    if cur != text:
        sys.stderr.write('gen-norm-data: %s is out of date\n' % OUT)
        sys.exit(1)
    sys.exit(0)
open(OUT, 'w', encoding='utf-8').write(text)
