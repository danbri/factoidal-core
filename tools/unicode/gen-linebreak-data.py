#!/usr/bin/env python3
"""Generate formal/lean4/L4Factoidal/Unicode/LineBreakData.lean (UAX #14 data).

Reads, from third_party/unicode-18.0.0/: LineBreak.txt (Line_Break; unlisted
code points take the `@missing` value XX), EastAsianWidth.txt (F, W, H set
a flag; unlisted code points take the `@missing` value N), emoji-data.txt
(Extended_Pictographic), DerivedGeneralCategory.txt (Cn, Mn, Mc, Pi, Pf).

  gen-linebreak-data.py          rewrite the module
  gen-linebreak-data.py --check  exit 1 if the committed module differs
"""
import os, sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
UCD = os.path.join(ROOT, "third_party", "unicode-18.0.0")
OUT = os.path.join(ROOT, "formal", "lean4", "L4Factoidal", "Unicode", "LineBreakData.lean")
MAX = 0x110000

CLASSES = ("AI AK AL AP AS B2 BA BB BK CB CJ CL CM CP CR EB EM EX GL H2 H3 HH HL HY "
           "ID IN IS JL JT JV LF NL NS NU OP PO PR QU RI SA SG SP SY VF VI WJ XX ZW ZWJ").split()
IDX = {c: i for i, c in enumerate(CLASSES)}


def rows(name):
    with open(os.path.join(UCD, name), encoding="utf-8") as f:
        for line in f:
            line = line.split("#", 1)[0].strip()
            if not line:
                continue
            a, b = [x.strip() for x in line.split(";")[:2]]
            if ".." in a:
                lo, hi = (int(x, 16) for x in a.split(".."))
            else:
                lo = hi = int(a, 16)
            yield lo, hi, b.split()[0]


def fill(arr, lo, hi, v):
    for c in range(lo, hi + 1):
        arr[c] = v


def merged(arr, skip_zero):
    """Ranges of equal value; value 0 is left out when skip_zero."""
    out = []
    start = 0
    for c in range(1, MAX + 1):
        if c == MAX or arr[c] != arr[start]:
            if arr[start] or not skip_zero:
                out.append("%X %X %d" % (start, c - 1, arr[start]))
            start = c
    return ";".join(out)


def build():
    # Defaults: the `@missing` lines of the two files (UAX #44 §4.2.10), XX for
    # Line_Break and N for East_Asian_Width. Both files list their unassigned
    # code points with a non-default value explicitly (for example
    # `1F02C..1F02F ; ID # Cn`). The header prose of LineBreak.txt 18.0.0 also
    # names 1F000..1FAFF as ID, but the data lines leave 1F8D9..1F8FF to
    # `@missing` (XX), and LineBreakTest.txt expects XX for U+1F8FF.
    lb = [IDX["XX"]] * MAX
    for lo, hi, v in rows("LineBreak.txt"):
        fill(lb, lo, hi, IDX[v])
    ea = [0] * MAX
    for lo, hi, v in rows("EastAsianWidth.txt"):
        fill(ea, lo, hi, 1 if v in ("F", "W", "H") else 0)
    ep = [0] * MAX
    for lo, hi, v in rows("emoji-data.txt"):
        if v == "Extended_Pictographic":
            fill(ep, lo, hi, 1)
    comb = [lb[c] | (ea[c] << 6) | (ep[c] << 7) for c in range(MAX)]
    gc = [0] * MAX
    gcv = {"Cn": 1, "Mn": 2, "Mc": 2, "Pi": 3, "Pf": 4}
    for lo, hi, v in rows("DerivedGeneralCategory.txt"):
        if v in gcv:
            fill(gc, lo, hi, gcv[v])
    return comb, gc


HEADER = """/-
L4Factoidal.Unicode.LineBreakData — generated by `tools/unicode/gen-linebreak-data.py`;
do not edit by hand (UAX #14 revision 57, Unicode 18.0.0,
https://github.com/danbri/factoidal/issues/1167, milestone 4).

Sources, all in `third_party/unicode-18.0.0/`: `LineBreak.txt` (Line_Break; unlisted
code points take the `@missing` value XX),
`EastAsianWidth.txt` (F, W, H set bit 6; unlisted code points take the `@missing` value N),
`emoji-data.txt` (Extended_Pictographic, bit 7), `DerivedGeneralCategory.txt`
(the second table: 1 Cn, 2 Mn or Mc, 3 Pi, 4 Pf, 0 other).

`lbTable` value: bits 0..5 the Line_Break class (the constants below), bit 6
East_Asian_Width in {F, W, H}, bit 7 Extended_Pictographic.
-/
import L4Factoidal.Unicode.RangeTable

namespace L4Factoidal.Unicode.LineBreakData

"""

FOOTER = """
#guard lbTable.get 0x41 &&& 63 == cAL
#guard lbTable.get 0x20 &&& 63 == cSP
#guard lbTable.get 0x3400 &&& 63 == cID
#guard lbTable.get 0x378 &&& 63 == cXX
#guard lbTable.get 0x3008 &&& 0x40 != 0
#guard lbTable.get 0x41 &&& 0x40 == 0
#guard lbTable.get 0x1F600 &&& 0x80 != 0
#guard gcTable.get 0x378 == 1
#guard gcTable.get 0x201C == 3
#guard gcTable.get 0x201D == 4
#guard gcTable.get 0x308 == 2

end L4Factoidal.Unicode.LineBreakData
"""


def render():
    comb, gc = build()
    out = [HEADER]
    for i, c in enumerate(CLASSES):
        out.append("@[inline] def c%s : UInt8 := %d\n" % (c, i))
    out.append("\n/-- Line_Break class names in constant order. -/\n")
    out.append("def classNames : Array String := #[%s]\n\n" % ", ".join('"%s"' % c for c in CLASSES))
    out.append('def lbTable : RangeTable := RangeTable.ofText "%s" %d\n\n' % (merged(comb, False), IDX["XX"]))
    out.append('def gcTable : RangeTable := RangeTable.ofText "%s"\n' % merged(gc, True))
    out.append(FOOTER)
    return "".join(out)


def main():
    text = render()
    if "--check" in sys.argv:
        try:
            with open(OUT, encoding="utf-8") as f:
                cur = f.read()
        except FileNotFoundError:
            cur = None
        if cur != text:
            sys.stderr.write("gen-linebreak-data: %s is out of date\n" % OUT)
            sys.exit(1)
        sys.exit(0)
    with open(OUT, "w", encoding="utf-8") as f:
        f.write(text)


main()
