#!/usr/bin/env python3
"""Generate formal/lean4/L4Factoidal/JS/FuelMonoSteps.lean from JS/Interp.lean.

For every function of the evaluator's main mutual block that takes fuel and answers in the
monad, it writes one field of the induction hypothesis `IH H n m` ("the function at fuel n is
Le the function at fuel m") and one step lemma (the body at n + 1 against m + 1, from IH n m),
then `IH_zero` and `IH_all` (fuel monotonicity of the whole block).

usage: fuelmono-gen.py Interp.lean out.lean [name,name,...]
With a list of names, only those step lemmas are written (and no IH_all). The committed file
is written with the list of the functions whose step the tactic proves today (see the file's
header), so `lake build L4Factoidal.JS.FuelMonoSteps` checks them.
"""
import re
import sys

src = open(sys.argv[1]).read().split('\n')
only = set(sys.argv[3].split(',')) if len(sys.argv) > 3 and sys.argv[3] else None
lo = next(i for i, l in enumerate(src) if l == 'mutual' and i > 1600)
hi = next(i for i in range(lo + 1, len(src)) if src[i] == 'end')


def split_top(s):
    out, d, cur, i = [], 0, '', 0
    while i < len(s):
        c = s[i]
        if c in '([{':
            d += 1
        if c in ')]}':
            d -= 1
        if d == 0 and s.startswith(' → ', i):
            out.append(cur)
            cur = ''
            i += 3
            continue
        cur += c
        i += 1
    out.append(cur)
    return out


fns = []
for i in range(lo, hi):
    m = re.match(r'^def (\w+) : (Nat → .*)$', src[i])
    if not m:
        continue
    parts = split_top(m.group(2))
    if not parts[-1].startswith('M '):
        continue
    fns.append((m.group(1), parts[1:-1]))


def binders(args):
    return ' '.join(f'(a{j} : {t})' for j, t in enumerate(args))


def apps(args):
    return ' '.join(f'a{j}' for j in range(len(args)))


def holes(args):
    return ' '.join('_' for _ in args)


out = []
w = out.append
w('import L4Factoidal.JS.FuelMono\n')
w('/-! # Fuel monotonicity of the evaluator\'s mutual block\n')
w('Generated by `tools/fuelmono-gen.py` from `JS/Interp.lean`; do not edit by hand. `IH H n m` says')
w('that every function of the block that takes fuel, at fuel `n`, is `Le` the same function at')
w('fuel `m`. Each step lemma proves a function\'s body at `n + 1` against `m + 1` from `IH H n m`,')
w('by walking the two bodies apart (`fuel_mono_pre`, `fuel_call`, `fuel_mono_post`). `IH_all` puts them together:')
w('fuel monotonicity of the whole block, for every heap (the register machine on or off). -/\n')
w('namespace L4Factoidal.JS.FuelMono\nopen L4Factoidal.JS\n')
w('set_option maxHeartbeats 4000000')
w('set_option linter.unusedVariables false\n')
w('/-- Every function of the block that takes fuel, at fuel `n` against fuel `m`. -/')
w('structure IH (H : Type) (n m : Nat) : Prop where')
for name, args in fns:
    q = f'∀ {binders(args)}, ' if args else ''
    w(f'  h_{name} : {q}Le ({name} (H := H) n {apps(args)}) ({name} m {apps(args)})')
w('')
w('/-- Close a call of a function of the block by its field of the induction hypothesis. -/')
w('syntax "fuel_call" ident : tactic')
w('macro_rules')
w('  | `(tactic| fuel_call $ih) => `(tactic| first')
for name, args in fns:
    w(f'      | with_reducible exact IH.h_{name} $ih {holes(args)}')
w('      )')
w('')
for name, args in fns:
    if only and name not in only:
        continue
    w(f'theorem {name}_step {{H : Type}} (n m : Nat) (ih : IH H n m) {binders(args)} :')
    w(f'    Le ({name} (H := H) (n + 1) {apps(args)}) ({name} (m + 1) {apps(args)}) := by')
    w(f'  refine Le.unfold ({name}.eq_def _ {holes(args)}) ({name}.eq_def _ {holes(args)}) ?_')
    w(f'  repeat\' (first | fuel_mono_pre | fuel_call ih | fuel_mono_post)\n')
if not only:
    w('/-- Out of fuel at 0: every function of the block but `iterResult`, which uses no fuel. -/')
    w('theorem IH_zero {H : Type} (m : Nat) : IH H 0 m where')
    for name, args in fns:
        lam = f'fun {apps(args)} => ' if args else ''
        if name == 'iterResult':
            w(f'  h_{name} := {lam}Le.unfold ({name}.eq_def _ {holes(args)}) ({name}.eq_def _ {holes(args)}) '
              '(by cases m <;> exact Le.refl _)')
        else:
            w(f'  h_{name} := {lam}Le.unfold ({name}.eq_def _ {holes(args)}) rfl (Le.fuel _)')
    w('')
    w('/-- Fuel monotonicity of the whole block: every function at fuel `n` against every `m ≥ n`. -/')
    w('theorem IH_all {H : Type} : (n m : Nat) → n ≤ m → IH H n m')
    w('  | 0, m, _ => IH_zero m')
    w('  | _ + 1, 0, h => absurd h (by omega)')
    w('  | n + 1, m + 1, h =>')
    w('    have ih := IH_all n m (by omega)')
    w('    { ' + ',\n      '.join(f'h_{name} := {name}_step n m ih' for name, _ in fns) + ' }')
    w('')
    w('''/-- Fuel monotonicity of statement lists, in the words of a run: from any heap (the register
machine on or off, any host and `hostCall`), if `evalStmts` at fuel `n` ends with anything but
`halt "fuel"`, it ends with the same result at every fuel `m ≥ n`: the same value or completion
and the same heap, so the same output, jobs, host state and steps left (a host call receives the
steps left, so it sees the same count at every call). -/
theorem evalStmts_fuel_mono {H : Type} {n m : Nat} (h : n ≤ m) (ctx : Ctx) (ss : List Stmt)
    (s : HeapOf H) (hn : ¬ Out (evalStmts n ctx ss s)) :
    evalStmts m ctx ss s = evalStmts n ctx ss s :=
  ((IH_all n m h).h_evalStmts ctx ss).eq_of_not_out s hn

/-- The same for a call of a function value. -/
theorem callV_fuel_mono {H : Type} {n m : Nat} (h : n ≤ m) (f thisV : Value) (args : Array Value)
    (s : HeapOf H) (hn : ¬ Out (callV n f thisV args s)) :
    callV m f thisV args s = callV n f thisV args s :=
  ((IH_all n m h).h_callV f thisV args).eq_of_not_out s hn

/-- The same for an expression. -/
theorem evalExpr_fuel_mono {H : Type} {n m : Nat} (h : n ≤ m) (ctx : Ctx) (e : Expr)
    (s : HeapOf H) (hn : ¬ Out (evalExpr n ctx e s)) :
    evalExpr m ctx e s = evalExpr n ctx e s :=
  ((IH_all n m h).h_evalExpr ctx e).eq_of_not_out s hn
''')
w('end L4Factoidal.JS.FuelMono')
open(sys.argv[2], 'w').write('\n'.join(out) + '\n')
print(len(fns), 'functions')
