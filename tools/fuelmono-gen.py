#!/usr/bin/env python3
"""Generate formal/lean4/L4Factoidal/JS/FuelMonoSteps.lean from JS/Interp.lean.

For every function of the evaluator's main mutual block that takes fuel and answers in the
monad, it writes one field of the induction hypothesis `IH H n m` ("the function at fuel n is
Le the function at fuel m") and one step lemma (the body at n + 1 against m + 1, from IH n m),
then `IH_zero` and `IH_all` (fuel monotonicity of the whole block).

usage: fuelmono-gen.py Interp.lean out.lean [name,name,...]
With a list of names, only those step lemmas are written (and no IH_all). The committed file
is written with the list of the functions whose step the tactic proves today (see the file's
header), so `lake build L4Factoidal.JS.FuelMonoSteps` checks them.
"""
import re
import sys

src = open(sys.argv[1]).read().split('\n')
split_mode = len(sys.argv) > 2 and sys.argv[2] == '--split'
only = None
if not split_mode:
    only = set(sys.argv[3].split(',')) if len(sys.argv) > 3 and sys.argv[3] else None
lo = next(i for i, l in enumerate(src) if l == 'mutual' and i > 1600)
hi = next(i for i in range(lo + 1, len(src)) if src[i] == 'end')


def split_top(s):
    out, d, cur, i = [], 0, '', 0
    while i < len(s):
        c = s[i]
        if c in '([{':
            d += 1
        if c in ')]}':
            d -= 1
        if d == 0 and s.startswith(' → ', i):
            out.append(cur)
            cur = ''
            i += 3
            continue
        cur += c
        i += 1
    out.append(cur)
    return out


fns = []
for i in range(lo, hi):
    m = re.match(r'^def (\w+) : (Nat → .*)$', src[i])
    if not m:
        continue
    parts = split_top(m.group(2))
    if not parts[-1].startswith('M '):
        continue
    # a dependent argument `(op : CoreOp H)` (coreRun) is bound by its type
    fns.append((m.group(1), [re.sub(r'^\((\w+) : (.*)\)$', r'\2', a) for a in parts[1:-1]]))


# A definition inside the block that takes no fuel calls none of the block's functions. There it
# would still take the block's `Mode` (a section variable) as a hidden argument, so the same
# condition would read differently on the two sides of a step (two modes) and the walk would
# split it twice. Such a helper is defined before the block.
strays = [m.group(2) for i in range(lo, hi)
          for m in [re.match(r'^(@\[[^\]]*\] )?def (\w+)\b', src[i])] if m and m.group(2) not in {n for n, _ in fns}]
if strays:
    sys.exit('fuelmono-gen: defined inside the evaluator\'s mutual block without a fuel argument: '
             + ', '.join(strays) + '. Move them before the block (before `section Block` in JS/Interp.lean).')


# functions whose walk needs a larger budget for `split` (see `fuel_walk`, JS/FuelMono.lean)
SPLIT_CAP = {'evalExpr': 400000}


def walk(name):
    return f'  fuel_walk {SPLIT_CAP[name]} ih\n' if name in SPLIT_CAP else '  fuel_walk ih\n'


# The goals a walk leaves at the sites of tiers 1 and 2 (`Le.withFast`, JS/FuelMono.lean): that the left
# run has the tier on only if the right has, and each fast path's soundness against the arm's own
# code (JS/Tier1Proofs.lean, JS/Tier2Proofs.lean). `ihs` is the hypothesis at every smaller fuel of the left run.
SITES = {
    'evalExpr': ['exact hb.1', 'exact Tier1Proofs.binary_site _ _ _ _ _ _', 'exact Tier1Proofs.update_site _ _ _ _ _ _ _ _',
                 'exact Tier1Proofs.setLocal_site _ _ _ _ _ _ _'],
    'vmLoop': ['exact hb.2', 'exact Tier2Proofs.getMember_site _ _ _ _ _ _ (fun v => ih.h_vmLoop _ _ _ _ _ _ _) _'],
    'evalStmt': ['exact hb.1', 'exact Tier1Proofs.block_site _ _ _ _ _ _ (fun j hj => (ihs j hj).h_evalStmts _ _)'],
}


def step(name, args):
    out = [f'theorem {name}_step {{H : Type}} (t1 t2 : Mode) (hb : t1.Sub t2) (n m : Nat)',
           f'    (ih : IH H t1 t2 n m) (ihs : ∀ k, k ≤ n → IH H t1 t2 k m) {binders(args)} :',
           f'    Le ({name} (H := H) (md := t1) (n + 1) {apps(args)}) ({name} (md := t2) (m + 1) {apps(args)}) := by',
           f'  refine Le.unfold ({name}.eq_def (md := t1) _ {holes(args)}) ({name}.eq_def (md := t2) _ {holes(args)}) ?_']
    if name in SITES:
        out.append(walk(name).rstrip('\n'))
        out.append('  all_goals first')
        for t in SITES[name]:
            out.append(f'    | {t}')
        out.append('')
    else:
        out.append(walk(name))
    return out


def binders(args):
    return ' '.join(f'(a{j} : {t})' for j, t in enumerate(args))


def apps(args):
    return ' '.join(f'a{j}' for j in range(len(args)))


def holes(args):
    return ' '.join('_' for _ in args)


out = []
w = out.append
w('import L4Factoidal.JS.FuelMono\n')
w('/-! # Fuel monotonicity of the evaluator\'s mutual block\n')
w('Generated by `tools/fuelmono-gen.py` from `JS/Interp.lean`; do not edit by hand. `IH H n m` says')
w('that every function of the block that takes fuel, at fuel `n`, is `Le` the same function at')
w('fuel `m`. Each step lemma proves a function\'s body at `n + 1` against `m + 1` from `IH H t1 t2 n m`,')
w('by walking the two bodies apart (`fuel_walk`). `IH_all` puts them together:')
w('fuel monotonicity of the whole block, for every heap (the register machine on or off). -/\n')
w('namespace L4Factoidal.JS.FuelMono\nopen L4Factoidal.JS\n')
w('set_option maxHeartbeats 0')
w('set_option linter.unusedVariables false\n')
w('/-- Every function of the block that takes fuel, in the mode `t1` at fuel `n` against the mode')
w('`t2` at fuel `m`. -/')
w('structure IH (H : Type) (t1 t2 : Mode) (n m : Nat) : Prop where')
for name, args in fns:
    q = f'∀ {binders(args)}, ' if args else ''
    w(f'  h_{name} : {q}Le ({name} (H := H) (md := t1) n {apps(args)}) ({name} (md := t2) m {apps(args)})')
w('')
# `fuel_call` (JS/FuelMono.lean) finds the field `IH.h_f` by the name of the call's head
w('')
for name, args in fns:
    if only and name not in only:
        continue
    for line in step(name, args):
        w(line)
if not only:
    w('/-- Out of fuel at 0: every function of the block but `iterResult`, which uses no fuel')
    w('(`vmLoop` puts the registers back in the heap first). -/')
    w('theorem IH_zero {H : Type} (t1 t2 : Mode) (m : Nat) : IH H t1 t2 0 m where')
    for name, args in fns:
        lam = f'fun {apps(args)} => ' if args else ''
        if name == 'iterResult':
            w(f'  h_{name} := {lam}Le.unfold ({name}.eq_def (md := t1) _ {holes(args)}) ({name}.eq_def (md := t2) _ {holes(args)}) '
              '(by cases m <;> exact Le.refl _)')
        elif name == 'vmLoop':
            # it first puts the registers back in the heap (`vmStash`), then is out of fuel
            w(f'  h_{name} := {lam}Le.unfold ({name}.eq_def (md := t1) _ {holes(args)}) rfl '
              '(Le.of_out fun _ => ⟨_, rfl⟩)')
        else:
            w(f'  h_{name} := {lam}Le.unfold ({name}.eq_def (md := t1) _ {holes(args)}) rfl (Le.fuel _)')
    w('')
    w('/-- Fuel monotonicity of the whole block: every function at fuel `n` against every `m ≥ n`. -/')
    w('theorem IH_all {H : Type} (t1 t2 : Mode) (hb : t1.Sub t2) :')
    w('    (m n : Nat) → n ≤ m → IH H t1 t2 n m')
    w('  | m, 0, _ => IH_zero t1 t2 m')
    w('  | 0, _ + 1, h => absurd h (by omega)')
    w('  | m + 1, n + 1, h =>')
    w('    have ih := IH_all t1 t2 hb m n (by omega)')
    w('    have ihs : ∀ k, k ≤ n → IH H t1 t2 k m := fun k hk => IH_all t1 t2 hb m k (by omega)')
    w('    { ' + ',\n      '.join(f'h_{name} := {name}_step t1 t2 hb n m ih ihs' for name, _ in fns) + ' }')
    w('')
    w('''/-- Fuel monotonicity of statement lists, in the words of a run: in any mode `t` and from any
heap (the register machine on or off, any host and `hostCall`), if `evalStmts` at fuel `n` ends
with anything but `halt "fuel"`, it ends with the same result at every fuel `m ≥ n`: the same
value or completion and the same heap, so the same output, jobs, host state and steps left (a
host call receives the steps left, so it sees the same count at every call). -/
theorem evalStmts_fuel_mono {H : Type} (t : Mode) {n m : Nat} (h : n ≤ m) (ctx : Ctx) (ss : List Stmt)
    (s : HeapOf H) (hn : ¬ Out (evalStmts (md := t) n ctx ss s)) :
    evalStmts (md := t) m ctx ss s = evalStmts (md := t) n ctx ss s :=
  ((IH_all t t (Mode.Sub.refl t) m n h).h_evalStmts ctx ss).eq_of_not_out s hn

/-- The same for a call of a function value. -/
theorem callV_fuel_mono {H : Type} (t : Mode) {n m : Nat} (h : n ≤ m) (f thisV : Value) (args : Array Value)
    (s : HeapOf H) (hn : ¬ Out (callV (md := t) n f thisV args s)) :
    callV (md := t) m f thisV args s = callV (md := t) n f thisV args s :=
  ((IH_all t t (Mode.Sub.refl t) m n h).h_callV f thisV args).eq_of_not_out s hn

/-- The same for an expression. -/
theorem evalExpr_fuel_mono {H : Type} (t : Mode) {n m : Nat} (h : n ≤ m) (ctx : Ctx) (e : Expr)
    (s : HeapOf H) (hn : ¬ Out (evalExpr (md := t) n ctx e s)) :
    evalExpr (md := t) m ctx e s = evalExpr (md := t) n ctx e s :=
  ((IH_all t t (Mode.Sub.refl t) m n h).h_evalExpr ctx e).eq_of_not_out s hn

/-- **Tiers 1 and 2 compose.** For every host, heap `s`, context and statement list: if the
reference (`Mode.ref`, the evaluator with no tier on) at fuel `n` ends with anything but
`halt "fuel"`, then the engine with tiers 1 and 2 on (`Mode.engine`) ends at every fuel `m ≥ n` with the same result:
the same value or completion and the same heap, so the same output, jobs, host state and steps
left at every host call. The two runs start from the same heap: the mode is a parameter of the
evaluator, not a field of the heap, and the function bodies in the heap are the same. -/
theorem tier1_evalStmts_refines {H : Type} {n m : Nat} (h : n ≤ m) (ctx : Ctx) (ss : List Stmt)
    (s : HeapOf H) (hn : ¬ Out (evalStmts (md := Mode.ref) n ctx ss s)) :
    evalStmts (md := Mode.engine) m ctx ss s = evalStmts (md := Mode.ref) n ctx ss s :=
  ((IH_all Mode.ref Mode.engine Mode.Sub.ref_engine m n h).h_evalStmts ctx ss).eq_of_not_out s hn

/-- The same for a call of a function value. -/
theorem tier1_callV_refines {H : Type} {n m : Nat} (h : n ≤ m) (f thisV : Value) (args : Array Value)
    (s : HeapOf H) (hn : ¬ Out (callV (md := Mode.ref) n f thisV args s)) :
    callV (md := Mode.engine) m f thisV args s = callV (md := Mode.ref) n f thisV args s :=
  ((IH_all Mode.ref Mode.engine Mode.Sub.ref_engine m n h).h_callV f thisV args).eq_of_not_out s hn

/-- The same for an expression. -/
theorem tier1_evalExpr_refines {H : Type} {n m : Nat} (h : n ≤ m) (ctx : Ctx) (e : Expr)
    (s : HeapOf H) (hn : ¬ Out (evalExpr (md := Mode.ref) n ctx e s)) :
    evalExpr (md := Mode.engine) m ctx e s = evalExpr (md := Mode.ref) n ctx e s :=
  ((IH_all Mode.ref Mode.engine Mode.Sub.ref_engine m n h).h_evalExpr ctx e).eq_of_not_out s hn

#print axioms IH_all
#print axioms evalStmts_fuel_mono
#print axioms callV_fuel_mono
#print axioms evalExpr_fuel_mono
#print axioms tier1_evalStmts_refines
#print axioms tier1_callV_refines
#print axioms tier1_evalExpr_refines
''')
w('end L4Factoidal.JS.FuelMono')
if not split_mode:
    open(sys.argv[2], 'w').write('\n'.join(out) + '\n')
else:
    # --split DIR GROUPS: GROUPS has lines "Tag: name,name,..." (one Lean process per group).
    # Writes DIR/FuelMonoIH.lean (the hypothesis and fuel_call), DIR/FuelMonoSteps<Tag>.lean per
    # group, each importing the one before (so a build checks them one after another, never two
    # large groups in memory at once), and, when the groups cover every function,
    # DIR/FuelMonoAll.lean with IH_zero, IH_all and the corollaries.
    d = sys.argv[3]
    groups = []
    for line in open(sys.argv[4]):
        line = line.strip()
        if not line or line.startswith('#'):
            continue
        tag, names = line.split(':', 1)
        groups.append((tag.strip(), [x.strip() for x in names.split(',') if x.strip()]))
    text = '\n'.join(out)
    hdr_end = text.index('\ntheorem ') + 1
    ih_part = text[:hdr_end].rstrip() + '\n\nend L4Factoidal.JS.FuelMono\n'
    # the steps of the block's wrappers use the built-ins' lemmas (`JS/FuelMonoNatives*.lean`)
    ih_part = ih_part.replace('import L4Factoidal.JS.FuelMono\n', 'import L4Factoidal.JS.FuelMonoNatives_callNative\nimport L4Factoidal.JS.Tier1Proofs\nimport L4Factoidal.JS.Tier2Proofs\n', 1)
    open(f'{d}/FuelMonoIH.lean', 'w').write(ih_part)
    known = {name: args for name, args in fns}
    prev = 'L4Factoidal.JS.FuelMonoIH'
    for tag, names in groups:
        g = [f'import {prev}\n', f'/-! Step lemmas of fuel monotonicity, group {tag}: generated by `tools/fuelmono-gen.py`. -/\n',
             'namespace L4Factoidal.JS.FuelMono\nopen L4Factoidal.JS\n', 'set_option maxHeartbeats 0',
             'set_option linter.unusedVariables false\n']
        for name in names:
            args = known[name]
            g.extend(step(name, args))
        g.append('end L4Factoidal.JS.FuelMono')
        open(f'{d}/FuelMonoSteps{tag}.lean', 'w').write('\n'.join(g) + '\n')
        prev = f'L4Factoidal.JS.FuelMonoSteps{tag}'
    covered = {x for _, names in groups for x in names}
    missing = [n for n, _ in fns if n not in covered]
    if not missing:
        tail = text[text.index('/-- Out of fuel at 0'):]
        open(f'{d}/FuelMonoAll.lean', 'w').write(f'import {prev}\n\nnamespace L4Factoidal.JS.FuelMono\nopen L4Factoidal.JS\n\n' + tail + '\n')
    print('groups', len(groups), 'missing', len(missing), ' '.join(missing))
print(len(fns), 'functions')
