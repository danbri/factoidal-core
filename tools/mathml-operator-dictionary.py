#!/usr/bin/env python3
"""Write formal/lean4/L4Factoidal/Rendering/Math/OperatorDictionaryData.lean from the vendored operator
dictionary of MathML Core appendix B (third_party/testing/mathml-operator-dictionary/operator-dictionary.json).

Each entry becomes (key, packed): key is "<content> <form>" as in the JSON; packed is
lspace + 8*rspace + 64*stretchy + 128*symmetric + 256*largeop + 512*movablelimits + 1024*horizontal,
with lspace and rspace the indices 0..7 (in 1/18 em; 5 when the entry gives none).
Run from the repository root; `--check` fails when the Lean file is not what this script writes."""
import json, sys
from pathlib import Path
ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "third_party/testing/mathml-operator-dictionary/operator-dictionary.json"
OUT = ROOT / "formal/lean4/L4Factoidal/Rendering/Math/OperatorDictionaryData.lean"

def lit(s):
    out = []
    for c in s:
        if c == '"': out.append('\\"')
        elif c == '\\': out.append('\\\\')
        elif ord(c) < 0x20 or ord(c) == 0x7f: out.append('\\x%02x' % ord(c))
        else: out.append(c)
    return '"' + ''.join(out) + '"'

def main():
    d = json.load(open(SRC, encoding="utf-8"))["dictionary"]
    rows = []
    for key in sorted(d):
        e = d[key]
        packed = (e.get("lspace", 5) + 8 * e.get("rspace", 5) + 64 * bool(e.get("stretchy")) +
                  128 * bool(e.get("symmetric")) + 256 * bool(e.get("largeop")) +
                  512 * bool(e.get("movablelimits")) + 1024 * bool(e.get("horizontal")))
        rows.append("  (%s, %d)" % (lit(key), packed))
    # Parts of 300 entries: a short array literal each.
    parts = [rows[i:i + 300] for i in range(0, len(rows), 300)]
    defs = "".join("private def part%d : Array (String × Nat) := #[\n%s]\n\n" % (i, ",\n".join(p))
                   for i, p in enumerate(parts))
    text = ("/-\nL4Factoidal.Rendering.Math.OperatorDictionaryData — the operator dictionary of MathML Core\n"
            "appendix B as data. GENERATED by tools/mathml-operator-dictionary.py from\n"
            "third_party/testing/mathml-operator-dictionary/operator-dictionary.json; do not edit.\n"
            "Each entry: the key \"<content> <form>\" and the packed properties (see the script).\n-/\n"
            "namespace L4Factoidal.Rendering.Math\n\n" + defs +
            "/-- " + str(len(rows)) + " entries, sorted by key. -/\n"
            "def operatorDictionaryData : Array (String × Nat) :=\n  " +
            " ++ ".join("part%d" % i for i in range(len(parts))) + "\n\n"
            "end L4Factoidal.Rendering.Math\n")
    if "--check" in sys.argv:
        if OUT.read_text(encoding="utf-8") != text:
            sys.exit("OperatorDictionaryData.lean is not what tools/mathml-operator-dictionary.py writes")
        return
    OUT.write_text(text, encoding="utf-8")
    print(len(rows), "entries")

main()
