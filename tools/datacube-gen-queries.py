#!/usr/bin/env python3
"""Generate formal/lean4/L4Factoidal/DataCube/Queries.lean from the SPARQL texts
vendored in tests/datacube/spec/ (extracted from the RDF Data Cube Recommendation
of 16 January 2014, sections 10.1 and 11.1; provenance in tests/datacube/PROVENANCE.md).

Usage: tools/datacube-gen-queries.py [OUT]   (default: the Lean file above)
tests/datacube/run.sh regenerates to a temporary path and fails when the
committed Lean file differs.
"""
import os
import sys

here = os.path.dirname(os.path.abspath(__file__))
root = os.path.dirname(here)
spec = os.path.join(root, "tests", "datacube", "spec")
local = os.path.join(root, "tests", "datacube", "local")
out = sys.argv[1] if len(sys.argv) > 1 else os.path.join(
    root, "formal", "lean4", "L4Factoidal", "DataCube", "Queries.lean")

FIXED = ["ic-1", "ic-2", "ic-3", "ic-4", "ic-5", "ic-6", "ic-7", "ic-8", "ic-9",
         "ic-10", "ic-11", "ic-12", "ic-13", "ic-14", "ic-15", "ic-16", "ic-17",
         "ic-18", "ic-19a", "ic-19b"]
OTHER = [("prefixes", "prefixes.rq"),
         ("ic20Instantiation", "ic-20-instantiation.rq"),
         ("ic20Template", "ic-20-template.rq"),
         ("ic21Instantiation", "ic-21-instantiation.rq"),
         ("ic21Template", "ic-21-template.rq"),
         ("normalizePhase1", "normalize-phase1.ru"),
         ("normalizePhase2", "normalize-phase2.ru"),
         ("ic17Sparql11", "../local/ic-17-sparql11.rq")]


def read(name):
    with open(os.path.join(spec, name), encoding="utf-8") as f:
        text = f.read()
    if not text.strip():
        sys.exit("datacube-gen-queries: empty file " + name)
    return text


def lean_string(text):
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n") + '"'


def ident(name):
    return "ic" + name[3:].replace("a", "A").replace("b", "B")


lines = [
    "/-",
    "L4Factoidal.DataCube.Queries — the SPARQL texts of the RDF Data Cube",
    "Recommendation (16 January 2014): the integrity-constraint ASK queries of",
    "section 11.1 and the normalization updates of section 10.1, verbatim.",
    "",
    "GENERATED by tools/datacube-gen-queries.py from tests/datacube/spec/; do not",
    "edit. tests/datacube/run.sh fails when this file and the generator disagree.",
    "`ic17Sparql11Text` is the one local text (tests/datacube/local/): IC-17 with",
    "the aggregate repeated in HAVING, see `Constraints.lean`.",
    "-/",
    "namespace L4Factoidal.DataCube.QB2014",
    "",
]
for name, fname in OTHER:
    lines.append("def %sText : String :=\n  %s\n" % (name, lean_string(read(fname))))
lines.append("/-- The fixed integrity-constraint queries, by constraint name. -/")
lines.append("def fixedQueryTexts : List (String × String) := [")
entries = []
for n in FIXED:
    entries.append("  (%s, %s)" % (lean_string(n.upper()), lean_string(read(n + ".rq"))))
lines.append(",\n".join(entries))
lines.append("]")
lines.append("")
lines.append("end L4Factoidal.DataCube.QB2014")
with open(out, "w", encoding="utf-8") as f:
    f.write("\n".join(lines) + "\n")
