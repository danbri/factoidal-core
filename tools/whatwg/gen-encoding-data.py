#!/usr/bin/env python3
"""Generate formal/lean4/L4Factoidal/WHATWG/Encoding/Data.lean from the
vendored WHATWG Encoding Standard resources in third_party/whatwg-encoding/
(encodings.json and indexes.json; provenance in PROVENANCE.md there).

Usage: python3 tools/whatwg/gen-encoding-data.py [--check]
With --check the script exits 1 if the committed file differs from the output.
"""
import json, os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SRC = os.path.join(ROOT, "third_party", "whatwg-encoding")
OUT = os.path.join(ROOT, "formal", "lean4", "L4Factoidal", "WHATWG", "Encoding", "Data.lean")

def ctor(name):
    return re.sub(r"[^a-z0-9]", "_", name.lower())

def chunks(s, n=4000):
    return [s[i:i + n] for i in range(0, len(s), n)] or [""]

def lean_str_join(s):
    parts = chunks(s)
    return "String.join [\n" + ",\n".join('  "%s"' % p for p in parts) + "]"

def index_text(vals):
    return ",".join("" if v is None else "%X" % v for v in vals)

def main():
    enc = json.load(open(os.path.join(SRC, "encodings.json")))
    idx = json.load(open(os.path.join(SRC, "indexes.json")))
    names, labels, single = [], [], []
    for group in enc:
        for e in group["encodings"]:
            names.append(e["name"])
            if group["heading"] == "Legacy single-byte encodings":
                single.append(e["name"])
            for l in e["labels"]:
                labels.append((l, e["name"]))
    o = []
    w = o.append
    w("/-\nL4Factoidal.WHATWG.Encoding.Data — generated by tools/whatwg/gen-encoding-data.py from\n"
      "the WHATWG Encoding Standard resources encodings.json and indexes.json\n"
      "(third_party/whatwg-encoding/, provenance in PROVENANCE.md there). Do not edit by hand.\n\n"
      "Index text format: the code points of pointers 0, 1, 2, ... in hexadecimal, separated\n"
      "by commas; an empty field is a pointer that is not in the index (index code point null).\n"
      "Index gb18030 ranges: `pointer:codepoint` pairs in hexadecimal, separated by commas.\n-/\n")
    w("namespace L4Factoidal.WHATWG.Encoding\n\n")
    w("/-- The %d encodings of the Encoding Standard, section 4.2 \"Names and labels\". -/\n" % len(names))
    w("inductive Encoding where\n")
    for n in names:
        w("  | %s\n" % ctor(n))
    w("  deriving DecidableEq, Repr, Inhabited, BEq\n\n")
    w("/-- The encoding's name, as in the table of section 4.2. -/\ndef Encoding.name : Encoding → String\n")
    for n in names:
        w("  | .%s => \"%s\"\n" % (ctor(n), n))
    w("\n/-- Every encoding, in the order of the table of section 4.2. -/\ndef Encoding.all : List Encoding :=\n  [")
    w(", ".join("." + ctor(n) for n in names))
    w("]\n\n")
    w("/-- The %d labels of section 4.2 with their encodings (labels are ASCII lowercase). -/\n" % len(labels))
    w("def labelTable : List (String × Encoding) := [\n")
    w(",\n".join('  ("%s", .%s)' % (l, ctor(n)) for l, n in labels))
    w("]\n\n")
    w("/-- The legacy single-byte encodings (section 9). -/\ndef Encoding.isSingleByte : Encoding → Bool\n")
    for n in single:
        w("  | .%s => true\n" % ctor(n))
    w("  | _ => false\n\n")
    for key in ["big5", "euc-kr", "gb18030", "jis0208", "jis0212", "iso-2022-jp-katakana"]:
        w("/-- index %s (%d pointers). -/\n" % (key, len(idx[key])))
        w("def indexText_%s : String := %s\n\n" % (ctor(key), lean_str_join(index_text(idx[key]))))
    rng = idx["gb18030-ranges"]
    w("/-- index gb18030 ranges (%d ranges). -/\n" % len(rng))
    w("def indexText_gb18030_ranges : String := %s\n\n" % lean_str_join(",".join("%X:%X" % (p, c) for p, c in rng)))
    w("/-- index single-byte for each legacy single-byte encoding (128 pointers each).\nISO-8859-8-I uses the index of ISO-8859-8 (section 9). -/\n")
    w("def singleByteIndexText : Encoding → String\n")
    for n in single:
        key = "iso-8859-8" if n == "ISO-8859-8-I" else n.lower()
        w("  | .%s => \"%s\"\n" % (ctor(n), index_text(idx[key])))
    w("  | _ => \"\"\n\n")
    w("end L4Factoidal.WHATWG.Encoding\n")
    text = "".join(o)
    if "--check" in sys.argv:
        cur = open(OUT).read() if os.path.exists(OUT) else ""
        if cur != text:
            print("gen-encoding-data: %s is stale; rerun the generator" % OUT, file=sys.stderr)
            sys.exit(1)
        return
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    open(OUT, "w").write(text)
    print("wrote %s (%d bytes, %d encodings, %d labels)" % (OUT, len(text), len(names), len(labels)))

main()
