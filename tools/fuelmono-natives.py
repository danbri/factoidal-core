#!/usr/bin/env python3
"""Write the fuel-monotonicity lemmas of the built-ins (namespace `Natives` of JS/Interp.lean), one
module and one Lean process per definition (issue 531).

After `tools/natives-split.py`, `Natives.moreNative` and `Natives.callNative` are a `match id with`
over calls of one definition per family of built-ins (`moreNativeBuffers`, `callNativeReflect`,
...). Each family gets the lemma `natives_<name>_mono` ("with two dispatchers related by `Le` at
every request, the built-in is related by `Le`"), proved by the walk over its body; the lemma of
a dispatcher follows from those of its families, which the walk finds by name
(`fuel_late_lemmas`, JS/FuelMono.lean).

The modules import one another in a chain, in the order of the definitions in the source, so a
build checks them one at a time. `iterEach` and `extraNative` are in `JS/FuelMonoNatives.lean`
(written by hand, the head of the chain).

usage: fuelmono-natives.py Interp.lean OUTDIR
"""
import re
import sys

src = open(sys.argv[1]).read().split('\n')
out = sys.argv[2]
lo = next(i for i, l in enumerate(src) if l == 'namespace Natives')
hi = next(i for i, l in enumerate(src) if l == 'end Natives')
BY_HAND = {'iterEach', 'extraNative'}



def binders(t):
    """`(a : T) (b : U (V))` as [(a, T), (b, U (V))]."""
    res, d, cur = [], 0, ''
    for c in t:
        if c == '(':
            d += 1
            if d == 1:
                cur = ''
                continue
        if c == ')':
            d -= 1
            if d == 0:
                a, ty = cur.split(' : ', 1)
                res.append((a, ty))
                continue
        cur += c
    return res


defs = []
for l in src[lo:hi]:
    m = re.match(r'def (\w+) \(core : CoreFn H\) (.*) : M Value := do$', l)
    if not m or m.group(1) in BY_HAND:
        continue
    defs.append((m.group(1), binders(m.group(2))))
# the dispatchers last: their lemmas use those of the families
order = [d for d in defs if d[0] not in ('moreNative', 'callNative')]
order += [d for d in defs if d[0] == 'moreNative'] + [d for d in defs if d[0] == 'callNative']

prev = 'L4Factoidal.JS.FuelMonoNatives'
for name, args in order:
    bind = ' '.join(f'({a} : {t})' for a, t in args)
    app = ' '.join(a for a, _ in args)
    what = 'from the lemmas of its families' if name in ('moreNative', 'callNative') else 'a family of built-ins'
    # `delta`, not `unfold`: `unfold` first makes the definition's equation lemmas, splitting its
    # matches (most of a minute and gigabytes for the larger families)
    t = [f'import {prev}', '',
         f'/-! Fuel monotonicity of `Natives.{name}` ({what}). Generated by',
         '`tools/fuelmono-natives.py`; do not edit by hand. -/', '',
         'namespace L4Factoidal.JS.FuelMono', 'open L4Factoidal.JS', '', 'variable {H : Type}', '',
         'set_option maxHeartbeats 0', 'set_option linter.unusedVariables false', '',
         f'theorem natives_{name}_mono {{c1 c2 : CoreFn H}} (hc : ∀ op, Le (c1 op) (c2 op))',
         f'    {bind} :',
         f'    Le (Natives.{name} c1 {app}) (Natives.{name} c2 {app}) := by',
         f'  delta Natives.{name}', '  fuel_walk', '', 'end L4Factoidal.JS.FuelMono', '']
    open(f'{out}/FuelMonoNatives_{name}.lean', 'w').write('\n'.join(t))
    prev = f'L4Factoidal.JS.FuelMonoNatives_{name}'
print(len(order), 'modules:', ' '.join(n for n, _ in order))
